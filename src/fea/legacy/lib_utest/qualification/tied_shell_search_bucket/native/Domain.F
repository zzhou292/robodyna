C Exact selected I2BUC1 fragments; shell association qualified separately.
      SUBROUTINE BUCKET_DOMAIN(NN,NRTM,NMN,X,IRECT,MSR,
     . MASTER_THICKNESS,SEGMENT_DATA,BOUND,CELL_NB,TZINF05,STATUS)
      USE CONSTANT_MOD
      USE, INTRINSIC :: IEEE_ARITHMETIC
      IMPLICIT NONE
      INTEGER NN,NRTM,NMN,IRECT(4,NRTM),MSR(NMN),CELL_NB(3),STATUS
      DOUBLE PRECISION X(3,NN),MASTER_THICKNESS(NRTM)
      DOUBLE PRECISION SEGMENT_DATA(NRTM,2),BOUND(6),TZINF05
      INTEGER L,I,J,N1,N2,N3,N4
      DOUBLE PRECISION DD,DX1,DY1,DZ1,DX3,DY3,DZ3,DSEARCH,
     . LOCAL_THKMAIN,THKSECND,THKMAIN,XMIN,XMAX,YMIN,YMAX,ZMIN,ZMAX,
     . MARGIN,DISTANCE(3),CELL_SIZE
      STATUS=1
      SEGMENT_DATA=ZERO
      DD=ZERO
      DSEARCH=ZERO
      THKSECND=ZERO
      THKMAIN=ZERO
      TZINF05=ZERO
#include "SearchDiagonals.inc"
      IF(.NOT.IEEE_IS_FINITE(DD).OR.DD<=ZERO) RETURN
      DO I=1,NRTM
        LOCAL_THKMAIN=MASTER_THICKNESS(I)
        THKMAIN=MAX(THKMAIN,LOCAL_THKMAIN)
#include "SearchThickness.inc"
      ENDDO
#include "SearchInflation.inc"
#include "InfluenceZone.inc"
#include "DomainBounds.inc"
C Range checks precede unchanged native integer conversion/product.
      CELL_SIZE=FOUR*DD
      IF(.NOT.IEEE_IS_FINITE(CELL_SIZE).OR.CELL_SIZE<=ZERO) RETURN
      IF(.NOT.ALL(IEEE_IS_FINITE(BOUND))) RETURN
      IF(ANY(BOUND(4:6)<=BOUND(1:3))) RETURN
      DISTANCE=BOUND(4:6)-BOUND(1:3)
      IF(.NOT.ALL(IEEE_IS_FINITE(DISTANCE))) RETURN
      IF(ANY(DISTANCE/CELL_SIZE>1000000D0)) RETURN
#include "CellCounts.inc"
      IF(PRODUCT(INT(CELL_NB,8))>1000000_8) RETURN
      STATUS=0
      END
