      SUBROUTINE L1_T3_FORCE(X,V,VR,MATERIAL,BASE_HISTORY,STEP,POINTS,OUTPUT,STATUS)
     . BIND(C,NAME="l1_t3_force")
      USE ISO_C_BINDING, ONLY: C_DOUBLE,C_INT
      USE T3_ENGINE_GEOMETRY_MOD, ONLY: T3_GEOMETRY_,T3_PREPARE_FRAME,
     . T3_PREPARE_RATES,T3_PACK_GEOMETRY
      USE T3_ENGINE_HISTORY_MOD, ONLY: T3_HISTORY_,T3_UNPACK_HISTORY,T3_PACK_HISTORY
      USE T3_ENGINE_MATERIAL_MOD, ONLY: T3_MATERIAL_,T3_PREPARE_MATERIAL
      USE L1_T3_SECTION_MOD, ONLY: L1_T3_MATERIAL,L1_T3_SECTION
      USE T3_ENGINE_STIFFNESS_MOD, ONLY: T3_NATIVE_STIFFNESS
#include "implicit_f.inc"
#include "mvsiz_p.inc"
#include "com01_c.inc"
#include "com08_c.inc"
      REAL(C_DOUBLE),INTENT(IN) :: X(3,3),V(3,3),VR(3,3),MATERIAL(4),BASE_HISTORY(26),STEP
      REAL(C_DOUBLE),INTENT(OUT) :: OUTPUT(92)
      INTEGER(C_INT),INTENT(OUT) :: STATUS
      REAL(C_DOUBLE),INTENT(INOUT) :: POINTS(5,3)
      TYPE(T3_GEOMETRY_) G
      TYPE(T3_HISTORY_) H
      TYPE(T3_MATERIAL_) M
      MY_REAL VISCMX(MVSIZ),DTEL(MVSIZ),NFOR(1,5),NMOM(1,3),
     . FORCE(MVSIZ,3,3),COUPLE(MVSIZ,3,3),FZERO(3,4,1),UNUSED(3,3)
      INTEGER J,K
      CALL T3_PREPARE_FRAME(X,V,VR,STEP,G,STATUS)
      IF(STATUS/=0) RETURN
      CALL T3_UNPACK_HISTORY(BASE_HISTORY,H)
      CALL L1_T3_MATERIAL(MATERIAL,G,H,M)
      CALL T3_PREPARE_RATES(G,STATUS)
      IF(STATUS/=0) RETURN
      CALL T3_PACK_GEOMETRY(G,OUTPUT(1:38))
      CALL L1_T3_SECTION(G,M,H,STEP,POINTS,VISCMX,STATUS)
      IF(STATUS/=0) RETURN
      CALL T3_NATIVE_STIFFNESS(G,M,VISCMX,DTEL)
      NFOR=ZERO
      NMOM=ZERO
      CALL C3SROTO3(1,1,G%ECOS,G%ESIN,H%FOR,H%MOM,NFOR,NMOM,1,1)
      FORCE=ZERO
      COUPLE=ZERO
      CALL C3FINT3(1,1,NFOR,NMOM,M%THK0,G%D(1,1),G%D(1,2),G%D(1,3),
     . FORCE(1,1,1),FORCE(1,1,2),FORCE(1,1,3),
     . FORCE(1,2,1),FORCE(1,2,2),FORCE(1,2,3),
     . FORCE(1,3,1),FORCE(1,3,2),FORCE(1,3,3),
     . COUPLE(1,1,1),COUPLE(1,1,2),COUPLE(1,1,3),
     . COUPLE(1,2,1),COUPLE(1,2,2),COUPLE(1,2,3),1)
      ISIGI=0
      NCYCLE=1
      IRUN=1
      TT=ZERO
      FZERO=ZERO
      UNUSED=ZERO
      CALL C3FCUM3(1,1,UNUSED,
     . FORCE(1,1,1),FORCE(1,1,2),FORCE(1,1,3),
     . FORCE(1,2,1),FORCE(1,2,2),FORCE(1,2,3),
     . FORCE(1,3,1),FORCE(1,3,2),FORCE(1,3,3),FZERO,
     . G%F(1,1,1),G%F(1,2,1),G%F(1,3,1),
     . G%F(1,1,2),G%F(1,2,2),G%F(1,3,2),
     . G%F(1,1,3),G%F(1,2,3),G%F(1,3,3))
      CALL C3MCUM3(1,1,UNUSED,
     . COUPLE(1,1,1),COUPLE(1,1,2),COUPLE(1,1,3),
     . COUPLE(1,2,1),COUPLE(1,2,2),COUPLE(1,2,3),
     . COUPLE(1,3,1),COUPLE(1,3,2),COUPLE(1,3,3),
     . G%F(1,1,1),G%F(1,2,1),G%F(1,3,1),
     . G%F(1,1,2),G%F(1,2,2),G%F(1,3,2),
     . G%F(1,1,3),G%F(1,2,3),G%F(1,3,3))
      H%ACTIVE=G%OFF(1)
      CALL T3_PACK_HISTORY(H,OUTPUT(39:64))
      DO J=1,3
        K=65+3*(J-1)
        OUTPUT(K:K+2)=FORCE(1,:,J)
        K=74+3*(J-1)
        OUTPUT(K:K+2)=COUPLE(1,:,J)
      ENDDO
      OUTPUT(83:92)=[M%THK0(1),M%SSP(1),M%DM,M%SHF(1),M%GS(1),
     . M%STI(1),M%STIR(1),DTEL(1),
     . H%EINT(1,1)-BASE_HISTORY(23),H%EINT(1,2)-BASE_HISTORY(24)]
      STATUS=0
      END
