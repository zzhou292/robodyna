      MODULE L1_T3_SECTION_MOD
      USE ISO_C_BINDING, ONLY: C_DOUBLE,C_INT
      USE T3_ENGINE_GEOMETRY_MOD, ONLY: T3_GEOMETRY_
      USE T3_ENGINE_MATERIAL_MOD, ONLY: T3_MATERIAL_,T3_PREPARE_MATERIAL
      USE T3_ENGINE_HISTORY_MOD, ONLY: T3_HISTORY_
      USE L1_SECTION_WORK_MOD, ONLY: L1_UPDATE_SECTION
#include "implicit_f.inc"
#include "mvsiz_p.inc"
      PRIVATE
      PUBLIC :: L1_T3_MATERIAL,L1_T3_SECTION
      CONTAINS
      SUBROUTINE L1_T3_MATERIAL(INPUT,G,H,M)
      REAL(C_DOUBLE),INTENT(IN) :: INPUT(4)
      TYPE(T3_GEOMETRY_),INTENT(IN) :: G
      TYPE(T3_HISTORY_),INTENT(IN) :: H
      TYPE(T3_MATERIAL_),INTENT(OUT) :: M
      INTEGER MAT(MVSIZ),PID(MVSIZ),IGEO(100,1)
      MY_REAL PM_STACK(20,1),THK_COPY(MVSIZ)
      CALL T3_PREPARE_MATERIAL(INPUT,G,H,M)
      MAT=1
      PID=1
      IGEO=0
      IGEO(11,1)=1
      PM_STACK=ZERO
      THK_COPY=H%THK
      CALL C3COEF3(1,1,M%PM,MAT,M%GEO,PID,G%OFF,G%AREA,
     . M%STI,M%STIR,M%SHF,M%THK0,M%THK02,M%NU,M%G,M%YM,
     . M%A11,M%A12,THK_COPY,M%SSP,M%RHO,M%VOL0,M%GS,
     . 1,1,3,-1,M%VOL00,IGEO,M%A11R,1,PM_STACK,1,M%ZOFFSET)
      END SUBROUTINE
      SUBROUTINE L1_T3_SECTION(G,M,H,STEP,POINTS,VISCMX,STATUS)
#include "scr14_c.inc"
      TYPE(T3_GEOMETRY_),INTENT(INOUT) :: G
      TYPE(T3_MATERIAL_),INTENT(IN) :: M
      TYPE(T3_HISTORY_),INTENT(INOUT) :: H
      REAL(C_DOUBLE),INTENT(IN) :: STEP
      REAL(C_DOUBLE),INTENT(INOUT) :: POINTS(5,3)
      MY_REAL,INTENT(OUT) :: VISCMX(MVSIZ)
      INTEGER(C_INT),INTENT(OUT) :: STATUS
      INTEGER MAT(MVSIZ),PID(MVSIZ)
      MY_REAL F_DEF(MVSIZ,8),EPSDOT(6,1),GSTRW(MVSIZ),BASIC(4),TOTAL_RATE
      IEPSDOT=0
      MAT=1
      PID=1
      F_DEF=ZERO
      EPSDOT=ZERO
      GSTRW=17.25D0
      VISCMX=ZERO
      CALL C3STRA3(1,1,M%PM,MAT,G%AREA,
     . G%DEF(1,1),G%DEF(1,2),G%DEF(1,3),G%DEF(1,5),G%DEF(1,4),
     . G%DEF(1,6),G%DEF(1,7),G%DEF(1,8),M%GEO,PID,M%NU,M%SHF,
     . H%STRA,M%SSP,M%RHO,EPSDOT,0,1,-1,
     . G%U(1,1,1),G%U(1,1,2),G%U(1,1,3),
     . G%U(1,2,1),G%U(1,2,2),G%U(1,2,3),
     . G%D(1,1),G%D(1,2),G%D(1,3),1,F_DEF,G%WXY,GSTRW,1)
      STATUS=2
      IF(GSTRW(1)/=17.25D0) RETURN
      BASIC=[M%RHO(1),M%YM(1),M%NU(1),M%GS(1)]
      CALL L1_UPDATE_SECTION(BASIC,STEP,M%THK0(1:1),
     . G%AREA(1:1),M%SSP(1:1),M%DM,G%DEF(1,:),POINTS,H%FOR,H%FOR_G,H%MOM,
     . H%THK(1:1),H%EINT,TOTAL_RATE,STATUS)
      IF(STATUS/=0) RETURN
      H%EPSD=ONE*TOTAL_RATE+(ONE-ONE)*H%EPSD
      VISCMX(1)=MAX(VISCMX(1),M%DM)
      END SUBROUTINE
      END MODULE
