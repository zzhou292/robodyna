      MODULE L1_QEPH_SECTION_MOD
      USE ISO_C_BINDING, ONLY: C_DOUBLE,C_INT
      USE QE_Q1_GEOMETRY_MOD, ONLY: QE_GEOMETRY_
      USE QE_Q2_MATERIAL_MOD, ONLY: QE_MATERIAL_,QE_PREPARE_MATERIAL
      USE QE_Q2_HISTORY_MOD, ONLY: QE_HISTORY_
      USE L1_SECTION_WORK_MOD, ONLY: L1_UPDATE_SECTION
#include "implicit_f.inc"
#include "mvsiz_p.inc"
      PRIVATE
      PUBLIC :: L1_QE_MATERIAL,L1_QE_SECTION
      CONTAINS
      SUBROUTINE L1_QE_MATERIAL(INPUT,AREA,THK,STEP,M)
      REAL(C_DOUBLE),INTENT(IN) :: INPUT(4),AREA(MVSIZ),THK(MVSIZ),STEP
      TYPE(QE_MATERIAL_),INTENT(OUT) :: M
      INTEGER MAT(MVSIZ),PID(MVSIZ),IGEO(100,1)
      MY_REAL GEO(200,1),THKE(MVSIZ),PM_STACK(20,1),UPARAM(14),
     . DIRA(MVSIZ,2),DIRB(MVSIZ,2),UVAR(MVSIZ,11),THK_COPY(MVSIZ)
! Reuse the qualified PM/context packing. Re-execute the complete coefficient
! leaf with selected MTN1/ITHK1/NPT3, replacing all effective coefficients.
      CALL QE_PREPARE_MATERIAL(INPUT,AREA,THK,STEP,M)
      MAT=1
      PID=1
      IGEO=0
      IGEO(11,1)=1
      GEO=ZERO
      GEO(13,1)=ZEP01+FIVEEM3
      GEO(17,1)=ONE
      GEO(38,1)=FIVE_OVER_6
      GEO(100,1)=SQRT(GEO(38,1))
      THKE=INPUT(4)
      THK_COPY=THK
      PM_STACK=ZERO
      UPARAM=ZERO
      DIRA=ZERO
      DIRB=ZERO
      UVAR=ZERO
      CALL CNCOEF3B(1,1,M%PM,MAT,GEO,PID,AREA,M%SHF,M%THK0,
     . M%THK02,M%NU,M%G,M%YM,M%A11,M%A12,THK_COPY,THKE,M%SSP,
     . M%RHO,M%VOL0,M%GS,1,1,3,M%DT1C,STEP,23,M%AMU,
     . M%GSR,M%A11SR,M%A12SR,M%NUSR,M%SHFSR,M%KRZ,IGEO,
     . M%A11R,1,PM_STACK,UPARAM,DIRA,DIRB,UVAR,M%FAC58,1,M%ZOFFSET)
      END SUBROUTINE
      SUBROUTINE L1_QE_SECTION(G,M,H,STEP,POINTS,VISCMX,ZCFAC,STATUS)
      TYPE(QE_GEOMETRY_),INTENT(IN) :: G
      TYPE(QE_MATERIAL_),INTENT(IN) :: M
      TYPE(QE_HISTORY_),INTENT(INOUT) :: H
      REAL(C_DOUBLE),INTENT(IN) :: STEP
      REAL(C_DOUBLE),INTENT(INOUT) :: POINTS(5,3)
      MY_REAL,INTENT(OUT) :: VISCMX(MVSIZ),ZCFAC(MVSIZ,2)
      INTEGER(C_INT),INTENT(OUT) :: STATUS
      MY_REAL DX(MVSIZ,8),F_DEF(MVSIZ,8),U(MVSIZ,2,4),EPSDOT(6,1),
     . WXY(MVSIZ),GSTRW(MVSIZ),BASIC(4),TOTAL_RATE
      DX=ZERO
      F_DEF=ZERO
      U=ZERO
      EPSDOT=ZERO
      WXY=ZERO
      GSTRW=ZERO
      VISCMX=ZERO
      CALL CZSTRA3(1,1,0,G%VDEF,H%STRA,
     . DX(1,1),DX(1,2),DX(1,3),DX(1,5),DX(1,4),
     . DX(1,6),DX(1,7),DX(1,8),M%DT1C,EPSDOT,0,1,
     . U(1,1,1),U(1,1,2),U(1,1,3),U(1,1,4),
     . U(1,2,1),U(1,2,2),U(1,2,3),U(1,2,4),
     . G%Y24,G%PX2,G%PY1,G%PY2,G%AREA,-1,1,WXY,F_DEF,GSTRW,1)
      BASIC=[M%RHO(1),M%YM(1),M%NU(1),M%GS(1)]
      CALL L1_UPDATE_SECTION(BASIC,STEP,M%THK0(1:1),
     . G%AREA(1:1),M%SSP(1:1),M%DM,DX(1,:),POINTS,H%FOR,H%FOR_G,H%MOM,
     . H%THK(1:1),H%EINT,TOTAL_RATE,STATUS)
      IF(STATUS/=0) RETURN
      VISCMX(1)=MAX(VISCMX(1),M%DM)
      ZCFAC(1,:)=ONE
      END SUBROUTINE
      END MODULE
