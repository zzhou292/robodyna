      SUBROUTINE NATIVE_POST_KINCHK(NNODE,IDS,FIVE,DECODE,NBODY,BODIES,NMEM,MEMBERS,
     . WALL_NODE,RBE2_NODE,RBE3_NODE,CYCLIC_NODE,PRINT_LEVEL,OUTPUT,OUTPUT_DECODE,KINET_OUT,STATS,STATUS)
     . BIND(C,NAME="native_post_kinchk")
      USE ISO_C_BINDING
      USE KINCHK_INTERFACES
      USE MESSAGE_MOD
      IMPLICIT NONE
#include "com04_c.inc"
#include "scr03_c.inc"
#include "units_c.inc"
#include "kincod_c.inc"
      INTEGER(C_INT), VALUE :: NNODE,NBODY,NMEM,WALL_NODE,RBE2_NODE,RBE3_NODE,CYCLIC_NODE,PRINT_LEVEL
      INTEGER(C_INT), INTENT(IN) :: IDS(NNODE),FIVE(5*NNODE),DECODE(8192),BODIES(5,NBODY),MEMBERS(NMEM)
      INTEGER(C_INT), INTENT(INOUT) :: OUTPUT(5*NNODE),OUTPUT_DECODE(8192),KINET_OUT(NNODE),STATS(5)
      INTEGER(C_INT), INTENT(OUT) :: STATUS
      INTEGER, ALLOCATABLE :: WORK(:),KINET(:),NPBY(:,:),NOM_OPT(:,:),LPBY(:),CYC(:)
      INTEGER IRBE2(5,1),IRBE3(9,1),LRBE2(1),LRBE3(1),NPRW(9),LPRW(1)
      INTEGER I,K,IOS,CLEAR_SUMMARY
      REAL(C_DOUBLE) RWL(8,1)
      CHARACTER(LEN=1024) LINE
      STATUS=1
      IF(NNODE<1.OR.NNODE>1048576.OR.NBODY<0.OR.NBODY>4096.OR.NMEM<0.OR.NMEM>4194304) RETURN
      IF(MIN(WALL_NODE,RBE2_NODE,RBE3_NODE,CYCLIC_NODE)<0) RETURN
      IF(MAX(WALL_NODE,RBE2_NODE,RBE3_NODE,CYCLIC_NODE)>NNODE) RETURN
      IF(PRINT_LEVEL/=0.AND.PRINT_LEVEL/=6) RETURN
      IF(ANY(IDS<=0).OR.ANY(FIVE(1:NNODE)<0).OR.ANY(FIVE(1:NNODE)>8191)) RETURN
      IF(ANY(FIVE(3*NNODE+1:5*NNODE)<0).OR.ANY(FIVE(3*NNODE+1:5*NNODE)>8191)) RETURN
      IF(ANY(DECODE<0).OR.ANY(DECODE>1)) RETURN
      IF(ANY(MEMBERS<1).OR.ANY(MEMBERS>NNODE)) RETURN
      K=0
      DO I=1,NBODY
        IF(BODIES(1,I)<1.OR.BODIES(1,I)>NNODE.OR.BODIES(2,I)/=K.OR.BODIES(3,I)<0) RETURN
        IF(BODIES(3,I)>NMEM-K.OR.MIN(BODIES(4,I),BODIES(5,I))<0) RETURN
        K=K+BODIES(3,I)
      ENDDO
      IF(K/=NMEM) RETURN
      NUMNOD=NNODE
      NRWALL=0
      IF(WALL_NODE>0) NRWALL=1
      NRWLP=8
      NNPBY=20
      NRBODY=NBODY
      NRBYKIN=NBODY
      NRBYLAG=0
      NRBE2=0
      NRBE3=0
      IF(RBE2_NODE>0) NRBE2=1
      IF(RBE3_NODE>0) NRBE3=1
      NRBE2L=5
      NRBE3L=9
      LNOPT1=2
      LTITR=1
      NBCSCYC=0
      IF(CYCLIC_NODE>0) NBCSCYC=1
      IPRI=PRINT_LEVEL
      KWARN=0
      IWARN=0
      KINCHK_WARNINGS=0
      KINCHK_ERRORS=0
      KINCHK_LAST_MESSAGE=0
      OPEN(NEWUNIT=IOUT,STATUS='SCRATCH',ACTION='READWRITE')
      ISTDO=IOUT
      ALLOCATE(WORK(5*NNODE),KINET(NNODE),CYC(NNODE),NPBY(NNPBY,MAX(1,NBODY)))
      ALLOCATE(NOM_OPT(LNOPT1,NBODY+3),LPBY(MAX(1,NMEM)))
      WORK=0
      CALL KININI(WORK)
      WORK=FIVE
      ITF=DECODE
      KINET=-777
      CYC=0
      IF(CYCLIC_NODE>0) CYC(CYCLIC_NODE)=1
      NPBY=0
      NOM_OPT=0
      DO I=1,NBODY+3
        NOM_OPT(1,I)=1000+I
      ENDDO
      DO I=1,NBODY
        NPBY(1,I)=BODIES(1,I)
        NPBY(2,I)=BODIES(3,I)
        NPBY(7,I)=BODIES(5,I)
        NPBY(20,I)=BODIES(4,I)
      ENDDO
      LPBY=0
      LPBY(1:NMEM)=MEMBERS
      NPRW=0
      LPRW=0
      RWL=0
      IF(WALL_NODE>0) THEN
        NPRW(1)=1
        LPRW(1)=WALL_NODE
      ENDIF
      IRBE2=0
      LRBE2=0
      IF(RBE2_NODE>0) IRBE2(3,1)=RBE2_NODE
      IRBE3=0
      LRBE3=0
      IF(RBE3_NODE>0) THEN
        IRBE3(3,1)=RBE3_NODE
        IRBE3(5,1)=1
        IRBE3(9,1)=-1
        LRBE3(1)=RBE3_NODE
      ENDIF
      CALL KINCHK(WORK,RWL,IDS,NPRW,LPRW,KINET,NPBY,LPBY,IRBE2,LRBE2,IRBE3,LRBE3,
     . NOM_OPT,NBODY,NBODY+1,NBODY+2,CYC)
      CLEAR_SUMMARY=0
      REWIND(IOUT)
      DO
        READ(IOUT,'(A)',IOSTAT=IOS) LINE
        IF(IOS/=0) EXIT
        IF(INDEX(LINE,'NO TRUE INCOMPATIBLE KINEMATIC CONDITION')>0) CLEAR_SUMMARY=1
      ENDDO
      CLOSE(IOUT)
      OUTPUT=WORK
      OUTPUT_DECODE=ITF
      KINET_OUT=KINET
      STATS(1)=KINCHK_WARNINGS
      STATS(2)=KINCHK_ERRORS
      STATS(3)=KINCHK_LAST_MESSAGE
      STATS(4)=CLEAR_SUMMARY
      STATS(5)=0
      IF(ALL(KINET/=-777)) STATS(5)=1
      STATUS=0
      END SUBROUTINE
