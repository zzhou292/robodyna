        DMN=LIMITS(1,K)
        DMX=LIMITS(2,K)
#include "extracted/ChannelCriterion.inc"
      ENDDO
#include "extracted/CoupledFailure.inc"
      RESULT=(/CRIT_NEW(1),OFF(1)/)
      END
