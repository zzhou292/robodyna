! Coherent one-cell selected CZFORC3 sequence, without whole-solver dispatch.
! Adapted from OpenRadioss (C) 2026 Siemens, AGPL-3.0-or-later.
! All leaf equations remain complete pinned extracts. Context/history adapters
! retain their explicit source provenance in the owning small modules.
      SUBROUTINE LR_QEPH_FORCE(X,V,VR,MATERIAL,BASE_HISTORY,STEP,
     . NPTS,CURVE,RATE_CONTROL,POINTS,SECTION_DIAG,
     . OUTPUT,IS_PLANAR,STATUS) BIND(C,NAME="lr_qeph_force")
      USE ISO_C_BINDING, ONLY: C_DOUBLE,C_INT
      USE QE_Q1_GEOMETRY_MOD, ONLY: QE_GEOMETRY_,QE_PREPARE_GEOMETRY,QE_PACK_GEOMETRY
      USE QE_Q2_HISTORY_MOD, ONLY: QE_HISTORY_,QE_UNPACK_HISTORY,QE_PACK_HISTORY
      USE QE_Q2_MATERIAL_MOD, ONLY: QE_MATERIAL_,QE_PREPARE_MATERIAL
      USE LR_QEPH_SECTION_MOD, ONLY: LR_QE_MATERIAL,LR_QE_SECTION
      USE QE_Q2_STIFFNESS_MOD, ONLY: QE_NATIVE_STIFFNESS
#include "implicit_f.inc"
#include "mvsiz_p.inc"
      REAL(C_DOUBLE),INTENT(IN) :: X(3,4),V(3,4),VR(3,4),MATERIAL(5),
     . BASE_HISTORY(38),STEP
      REAL(C_DOUBLE),INTENT(OUT) :: OUTPUT(152)
      INTEGER(C_INT),INTENT(OUT) :: IS_PLANAR,STATUS
      INTEGER(C_INT),VALUE :: NPTS
      REAL(C_DOUBLE),INTENT(IN) :: CURVE(2,NPTS+1),RATE_CONTROL(3)
      REAL(C_DOUBLE),INTENT(INOUT) :: POINTS(7,3)
      REAL(C_DOUBLE),INTENT(OUT) :: SECTION_DIAG(8)
      TYPE(QE_GEOMETRY_) GEOMETRY
      TYPE(QE_HISTORY_) H
      TYPE(QE_MATERIAL_) M
      MY_REAL VISCMX(MVSIZ),ZCFAC(MVSIZ,2),STI(MVSIZ),STIR(MVSIZ),DTEL(MVSIZ),
     . VF(MVSIZ,3,4),VM(MVSIZ,2,4),FORCE(MVSIZ,3,4),COUPLE(MVSIZ,3,4),
     . SIGY(MVSIZ),FAC1(MVSIZ),FZERO(3,4,1),VMZ(MVSIZ,4)
      INTEGER IPARTC(MVSIZ),J,K
      CALL QE_PREPARE_GEOMETRY(X,V,VR,MATERIAL(4),STEP,GEOMETRY,STATUS)
      IF(STATUS/=0) RETURN
! Preserve exactly the Q1 pre-CNDT3 geometry/rate diagnostics.
      CALL QE_PACK_GEOMETRY(X,GEOMETRY,OUTPUT(1:80),IS_PLANAR)
      CALL QE_UNPACK_HISTORY(BASE_HISTORY,H)
      CALL LR_QE_MATERIAL(MATERIAL(1:4),GEOMETRY%AREA,H%THK,STEP,M)
      CALL LR_QE_SECTION(GEOMETRY,M,H,STEP,NPTS,CURVE,RATE_CONTROL,
     . POINTS,SECTION_DIAG,VISCMX,ZCFAC,STATUS)
      IF(STATUS/=0) RETURN
      CALL QE_NATIVE_STIFFNESS(GEOMETRY,M,MATERIAL(5),VISCMX,STI,STIR,DTEL)
      VF=ZERO
      VM=ZERO
      SIGY=SECTION_DIAG(7)
      FAC1=ONE
      IPARTC=1
      FZERO=ZERO
      VMZ=ZERO
      FORCE=ZERO
      COUPLE=ZERO
      CALL CZFINTCE(1,1,M%THK0,M%THK02,GEOMETRY%AREA_I,
     . GEOMETRY%X13,GEOMETRY%X24,GEOMETRY%Y13,GEOMETRY%Y24,GEOMETRY%Z1,
     . GEOMETRY%MX23,GEOMETRY%MX13,GEOMETRY%MX34,
     . GEOMETRY%MY13,GEOMETRY%MY23,GEOMETRY%MY34,H%FOR,H%MOM,VF,VM,1)
! DHG in CZFORC3 is a rate array; CZFINTN1 itself multiplies it by STEP.
! NIP3, LAW44; native ETSE factors and last-point yield; all 12 HOURG states.
      CALL CZFINTN1(1,1,M%THK0,M%THK02,GEOMETRY%AREA_I,GEOMETRY%VHG,
     . GEOMETRY%X13,GEOMETRY%X24,GEOMETRY%Y13,GEOMETRY%Y24,GEOMETRY%Z1,
     . GEOMETRY%MX23,GEOMETRY%MX13,GEOMETRY%MX34,
     . GEOMETRY%MY13,GEOMETRY%MY23,GEOMETRY%MY34,H%HOURG,H%FOR,H%MOM,
     . VF,VM,ZCFAC,M%A11,M%A12,M%G,M%SHF,SIGY,GEOMETRY%OFF,FAC1,
     . M%RHO,GEOMETRY%AREA,STEP,H%EINT,M%AMU,GEOMETRY%VHI,3,IPARTC,
     . H%EVIS,0,M%GSR,1,M%A11SR,M%A12SR,M%NUSR,M%SHFSR,44,M%FAC58)
! Selected CZPROJ1 dispatch: ISIGI0/IVECTOR0 => IFINI0, full CZPROJN.
! Native positive internal force/couple convention is preserved for CUPDTN3.
      CALL CZPROJN(1,1,GEOMETRY%VQN,GEOMETRY%VQ,VF,VM,GEOMETRY%PLAT,
     . FORCE(1,1,1),FORCE(1,1,2),FORCE(1,1,3),FORCE(1,1,4),
     . FORCE(1,2,1),FORCE(1,2,2),FORCE(1,2,3),FORCE(1,2,4),
     . FORCE(1,3,1),FORCE(1,3,2),FORCE(1,3,3),FORCE(1,3,4),
     . COUPLE(1,1,1),COUPLE(1,1,2),COUPLE(1,1,3),COUPLE(1,1,4),
     . COUPLE(1,2,1),COUPLE(1,2,2),COUPLE(1,2,3),COUPLE(1,2,4),
     . COUPLE(1,3,1),COUPLE(1,3,2),COUPLE(1,3,3),COUPLE(1,3,4),
     . FZERO,GEOMETRY%Z1,GEOMETRY%COREL,GEOMETRY%DI,GEOMETRY%DB,0,0,
     . GEOMETRY%DIZ,VMZ)
      H%ACTIVE=GEOMETRY%OFF(1)
      CALL QE_PACK_HISTORY(H,OUTPUT(81:118))
      DO J=1,4
        K=119+3*(J-1)
        OUTPUT(K:K+2)=FORCE(1,:,J)
        K=131+3*(J-1)
        OUTPUT(K:K+2)=COUPLE(1,:,J)
      END DO
      OUTPUT(143:152)=[M%THK0(1),M%SSP(1),M%DM,M%AMU(1),STI(1),STIR(1),
     . DTEL(1),H%EINT(1,1)-BASE_HISTORY(35),H%EINT(1,2)-BASE_HISTORY(36),
     . H%EVIS(8,1)-BASE_HISTORY(37)]
      STATUS=0
      END
