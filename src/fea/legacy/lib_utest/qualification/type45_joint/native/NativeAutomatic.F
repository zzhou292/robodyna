        DOUBLE PRECISION VAR(39)
      END TYPE
      TYPE(BUFFER) GBUF
      INTEGER N1,N2,M1,M2,IRB1,IRB2,FLAG_S,NV,J,IXR(6,1)
      DOUBLE PRECISION ALPHA,XL,XX1,XX2,XX,MASS1,INER1,KM1,KRM1,
