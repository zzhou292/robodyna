! Bounded test adapter. All native array indices received here are one-based.
      SUBROUTINE NATIVE_CLASSIFY(NNODE,NROLE,ITAB,INPUT_KINE,ROLE,
     . NSL,NML,SLAVES,MASTERS,NSEC,SECTION,NSECND,SECTION_NODES,
     . CYCLIC_ENABLED,CYCLIC,NTET,TETRA,TAGS,NBE2,BE2,NBE3,
     . BE3_COUNTS,NBE3ND,BE3_NODES,OUTPUT_KINE,IRUPT_OUT,ITF_OUT,
     . WARNINGS,PENALTIES,STATUS) BIND(C,NAME="native_classify")
      USE ISO_C_BINDING
      USE CLASSIFICATION_INTERFACES
      USE MESSAGE_MOD
      IMPLICIT NONE
#include "com04_c.inc"
#include "scr03_c.inc"
#include "units_c.inc"
#include "kincod_c.inc"
      INTEGER(C_INT), VALUE :: NNODE,NROLE,NSL,NML,NSEC,NSECND
      INTEGER(C_INT), VALUE :: CYCLIC_ENABLED,NTET,NBE2,NBE3,NBE3ND
      INTEGER(C_INT), INTENT(IN) :: ITAB(NNODE),INPUT_KINE(5*NNODE)
      INTEGER(C_INT), INTENT(IN) :: ROLE(5,NROLE),SLAVES(NSL),MASTERS(NML)
      INTEGER(C_INT), INTENT(IN) :: SECTION(2,NSEC),SECTION_NODES(NSECND)
      INTEGER(C_INT), INTENT(IN) :: CYCLIC(NNODE),TETRA(3,NTET),TAGS(NNODE)
      INTEGER(C_INT), INTENT(IN) :: BE2(NBE2),BE3_COUNTS(NBE3),BE3_NODES(NBE3ND)
      INTEGER(C_INT), INTENT(OUT) :: OUTPUT_KINE(5*NNODE),IRUPT_OUT(NSL),ITF_OUT(8192)
      INTEGER(C_INT), INTENT(OUT) :: WARNINGS,PENALTIES,STATUS
      INTEGER, ALLOCATABLE :: IPARI(:,:),NOM_OPT(:,:),NSTRF(:)
      INTEGER, ALLOCATABLE :: IRBE2(:,:),IRBE3(:,:),WORK(:)
      TYPE(INTBUF_STRUCT_), ALLOCATABLE :: BUFFERS(:)
      INTEGER I,K,J,S,M,NWORDS
      STATUS=1
      IF(NNODE<=0.OR.NROLE<=0.OR.MIN(NSL,NML,NSEC,NSECND,NTET,NBE2,NBE3,NBE3ND)<0) RETURN
      IF(NNODE>1048576.OR.NROLE>4096.OR.NSEC>4096) RETURN
      IF(MAX(NSL,NML,NSECND,NTET,NBE2,NBE3,NBE3ND)>4194304) RETURN
      IF(ANY(ROLE(4:5,:)<0).OR.ANY(SECTION(2,:)<0).OR.ANY(BE3_COUNTS<0)) RETURN
      IF(SUM(INT(ROLE(4,:),C_INT64_T))/=NSL.OR.SUM(INT(ROLE(5,:),C_INT64_T))/=NML) RETURN
      IF(SUM(INT(SECTION(2,:),C_INT64_T))/=NSECND.OR.SUM(INT(BE3_COUNTS,C_INT64_T))/=NBE3ND) RETURN
      IF(CYCLIC_ENABLED<0.OR.CYCLIC_ENABLED>1.OR.ANY(CYCLIC<0).OR.ANY(CYCLIC>HUGE(1)-13)) RETURN
      IF(ANY(SLAVES<1).OR.ANY(SLAVES>NNODE).OR.ANY(MASTERS<1).OR.ANY(MASTERS>NNODE)) RETURN
      IF(ANY(SECTION_NODES<1).OR.ANY(SECTION_NODES>NNODE)) RETURN
      IF(ANY(TETRA<1).OR.ANY(TETRA>NNODE).OR.ANY(TAGS< -NTET).OR.ANY(TAGS>NTET)) RETURN
      IF(ANY(BE2<1).OR.ANY(BE2>NNODE).OR.ANY(BE3_NODES<1).OR.ANY(BE3_NODES>NNODE)) RETURN
      IF(ANY(INPUT_KINE(1:NNODE)<0).OR.ANY(INPUT_KINE(1:NNODE)>8191)) RETURN
      IF(ANY(INPUT_KINE(3*NNODE+1:5*NNODE)<0).OR.ANY(INPUT_KINE(3*NNODE+1:5*NNODE)>8191)) RETURN
      IF(ANY(INPUT_KINE(NNODE+1:3*NNODE)<0).OR.ANY(MOD(INPUT_KINE(NNODE+1:3*NNODE),10)>7)) RETURN
      NUMNOD=NNODE
      NINTER=NROLE
      NPARI=20
      LNOPT1=2
      LTITR=1
      NBCSCYC=CYCLIC_ENABLED
      NSECT=NSEC
      NS10E=NTET
      NRBE2L=3
      NRBE2=NBE2
      NRBE3L=5
      NRBE3=NBE3
      SLRBE3=NBE3ND
      KWARN=0
      IPRI=0
      PENALTY_COUNT=0
      ERR_CATEGORY=''
      OPEN(NEWUNIT=IOUT,STATUS='SCRATCH',ACTION='WRITE')
      ALLOCATE(WORK(5*NNODE))
      WORK=0
      CALL KININI(WORK)
      WORK=INPUT_KINE
      ALLOCATE(IPARI(NPARI,NROLE),NOM_OPT(LNOPT1,NROLE),BUFFERS(NROLE))
      IPARI=0
      NOM_OPT=0
      S=0
      M=0
      DO I=1,NROLE
        IPARI(15,I)=ROLE(1,I)
        IPARI(7,I)=ROLE(2,I)
        IPARI(20,I)=ROLE(3,I)
        IPARI(5,I)=ROLE(4,I)
        IPARI(6,I)=ROLE(5,I)
        NOM_OPT(1,I)=ROLE(1,I)
        ALLOCATE(BUFFERS(I)%NSV(ROLE(4,I)),BUFFERS(I)%IRUPT(ROLE(4,I)))
        ALLOCATE(BUFFERS(I)%MSR(ROLE(5,I)))
        BUFFERS(I)%NSV=SLAVES(S+1:S+ROLE(4,I))
        BUFFERS(I)%MSR=MASTERS(M+1:M+ROLE(5,I))
        BUFFERS(I)%IRUPT=0
        S=S+ROLE(4,I)
        M=M+ROLE(5,I)
      ENDDO
      NWORDS=25+30*NSEC+NSECND
      ALLOCATE(NSTRF(NWORDS))
      NSTRF=0
      NSTRF(25)=26
      K=26
      S=0
      DO I=1,NSEC
        NSTRF(K)=SECTION(1,I)
        NSTRF(K+6)=SECTION(2,I)
        DO J=1,SECTION(2,I)
          NSTRF(K+29+J)=SECTION_NODES(S+J)
        ENDDO
        NSTRF(K+24)=K+30+SECTION(2,I)
        K=K+30+SECTION(2,I)
        S=S+SECTION(2,I)
      ENDDO
      ALLOCATE(IRBE2(3,NBE2),IRBE3(5,NBE3))
      IRBE2=0
      IRBE2(3,:)=BE2
      IRBE3=0
      K=0
      DO I=1,NBE3
        IRBE3(1,I)=K
        IRBE3(5,I)=BE3_COUNTS(I)
        K=K+BE3_COUNTS(I)
      ENDDO
      CALL ITAGSL2(IPARI,NOM_OPT,ITAB,WORK,BUFFERS,TAGS,TETRA,
     .             NSTRF,CYCLIC,IRBE2,IRBE3,BE3_NODES)
      OUTPUT_KINE=WORK
      K=0
      DO I=1,NROLE
        IRUPT_OUT(K+1:K+ROLE(4,I))=BUFFERS(I)%IRUPT
        K=K+ROLE(4,I)
      ENDDO
      ITF_OUT=ITF
      WARNINGS=KWARN
      PENALTIES=PENALTY_COUNT
      CLOSE(IOUT)
      STATUS=0
      END SUBROUTINE
