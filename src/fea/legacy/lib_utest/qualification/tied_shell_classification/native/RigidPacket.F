      SUBROUTINE NATIVE_RIGID(NNODE,NGROUP,ITAB,INPUT_KINE,COUNTS,
     . NMEMBER,LPBY,IDDLEVEL,IKREM,OUTPUT_KINE,ITF_OUT,WARNINGS,STATUS)
     . BIND(C,NAME="native_rigid")
      USE ISO_C_BINDING
      USE CLASSIFICATION_INTERFACES
      IMPLICIT NONE
#include "com04_c.inc"
#include "scr03_c.inc"
#include "kincod_c.inc"
      INTEGER(C_INT),VALUE :: NNODE,NGROUP,NMEMBER,IDDLEVEL,IKREM
      INTEGER(C_INT),INTENT(IN) :: ITAB(NNODE),INPUT_KINE(5*NNODE),COUNTS(NGROUP),LPBY(NMEMBER)
      INTEGER(C_INT),INTENT(OUT) :: OUTPUT_KINE(5*NNODE),ITF_OUT(8192),WARNINGS,STATUS
      INTEGER,ALLOCATABLE :: IKINE(:),IKINE1(:)
      INTEGER N,NSL,J,K,IDIR
      STATUS=1
      IF(NNODE<=0.OR.MIN(NGROUP,NMEMBER,IDDLEVEL)<0) RETURN
      IF(NNODE>1048576.OR.NGROUP>4194304.OR.NMEMBER>4194304) RETURN
      IF(ANY(COUNTS<0).OR.SUM(INT(COUNTS,C_INT64_T))/=NMEMBER) RETURN
      IF(ANY(LPBY<1).OR.ANY(LPBY>NNODE)) RETURN
      IF(ANY(INPUT_KINE(1:NNODE)<0).OR.ANY(INPUT_KINE(1:NNODE)>8191)) RETURN
      IF(ANY(INPUT_KINE(3*NNODE+1:5*NNODE)<0).OR.ANY(INPUT_KINE(3*NNODE+1:5*NNODE)>8191)) RETURN
      IF(ANY(INPUT_KINE(NNODE+1:3*NNODE)<0).OR.ANY(MOD(INPUT_KINE(NNODE+1:3*NNODE),10)>7)) RETURN
      NUMNOD=NNODE
      KWARN=0
      IPRI=0
      ERR_CATEGORY=''
      ALLOCATE(IKINE(5*NNODE),IKINE1(3*NNODE))
      IKINE=0
      IKINE1=0
      CALL KININI(IKINE)
      IKINE=INPUT_KINE
      K=0
      DO N=1,NGROUP
        NSL=COUNTS(N)
#include "RigidRegistration.inc"
        K=K+NSL
      ENDDO
      OUTPUT_KINE=IKINE
      ITF_OUT=ITF
      WARNINGS=KWARN
      STATUS=0
      END SUBROUTINE
