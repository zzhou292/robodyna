! Independent complete-leaf C3FORC3/CMAIN3/MULAWC selected composition.
! Caller owns endpoint time; each oracle retains its own 37-value history.
      SUBROUTINE T3_ONE_POINT_NATIVE(MFUNC,NPTS,ISRATE,CURVE,BASIC,LINEAR,
     . CONTROLS,D1,STEP,TIME,X,V,VR,STATE,OUTPUT,STATUS)
     . BIND(C,NAME='t3_one_point_native')
      USE ISO_C_BINDING,ONLY:C_DOUBLE,C_INT
      USE T3_ENGINE_GEOMETRY_MOD,ONLY:T3_GEOMETRY_,T3_PACK_GEOMETRY
      USE T3_ENGINE_HISTORY_MOD,ONLY:T3_HISTORY_,T3_UNPACK_HISTORY,T3_PACK_HISTORY
      USE T3_ENGINE_MATERIAL_MOD,ONLY:T3_MATERIAL_
      USE ONE_POINT_GEOMETRY,ONLY:ONE_POINT_FRAME,ONE_POINT_RATES
      USE ONE_POINT_COEFFICIENTS_MOD,ONLY:ONE_POINT_COEFFICIENTS
      USE ONE_POINT_STIFFNESS_MOD,ONLY:ONE_POINT_STIFFNESS
      USE ONE_POINT_PARENT_MOD,ONLY:ONE_POINT_PARENT
      USE MEMBRANE_LAW44_CALLER,ONLY:MembranePoint,MembraneForceWork
#include "implicit_f.inc"
#include "mvsiz_p.inc"
#include "scr14_c.inc"
      INTEGER(C_INT),VALUE::MFUNC,NPTS,ISRATE
      REAL(C_DOUBLE),INTENT(IN)::CURVE(2,NPTS+1),BASIC(3),LINEAR(2),CONTROLS(3),
     . D1,STEP,TIME,X(3,3),V(3,3),VR(3,3)
      REAL(C_DOUBLE),INTENT(INOUT)::STATE(37)
      REAL(C_DOUBLE),INTENT(OUT)::OUTPUT(126)
      INTEGER(C_INT),INTENT(OUT)::STATUS
      TYPE(T3_GEOMETRY_) G
      TYPE(T3_HISTORY_) H
      TYPE(T3_MATERIAL_) M
      TYPE RATE_STORAGE
        MY_REAL THK(1),EPSD(1)
      END TYPE
      TYPE(RATE_STORAGE) GBUF
      INTEGER,PARAMETER::NEL=1
      INTEGER I,J,K,MAT(MVSIZ),PID(MVSIZ),FLAGS(1)
      MY_REAL INPUT(4),F_DEF(MVSIZ,8),EPSDOT(6,1),GSTRW(MVSIZ),
     . POINT(7),FAILED(3),VALUES(13),WPLA,OLD_WPLA,OLD_EINT(2),OLD_OFF,
     . VISCMX(MVSIZ),DTEL(MVSIZ),FORCE(MVSIZ,3,3),COUPLE(MVSIZ,3,3),
     . EXX(1),EYY(1),EXY(1),KXX(1),KYY(1),KXY(1),
     . DT1,DTINV,ASRATE,EPS_K2,EPS_M2,EPSD_PG(1),DT1C(1),
     . DEPS(5),ZPOSITION,PARENT,WEIGHTS(1)
      CALL T3_UNPACK_HISTORY(STATE(1:26),H)
      POINT=STATE(27:33)
      FAILED=STATE(34:36)
      WPLA=STATE(37)
      OLD_WPLA=WPLA
      OLD_EINT=H%EINT(1,:)
      OLD_OFF=H%ACTIVE
      CALL ONE_POINT_FRAME(X,V,VR,STEP,OLD_OFF,G,STATUS)
      IF(STATUS/=0) RETURN
      INPUT=[BASIC(1),BASIC(2),BASIC(3),H%THK(1)]
      CALL ONE_POINT_COEFFICIENTS(INPUT,G,H,M)
      CALL ONE_POINT_RATES(G,STATUS)
      IF(STATUS/=0) RETURN
      CALL T3_PACK_GEOMETRY(G,OUTPUT(1:38))
      IEPSDOT=0
      MAT=1
      PID=1
      F_DEF=ZERO
      EPSDOT=ZERO
      GSTRW=17.25D0
! Actual NPG1/ISMSTR2: native preserves all eight strain/curvature entries.
      CALL C3STRA3(1,1,M%PM,MAT,G%AREA,
     . G%DEF(1,1),G%DEF(1,2),G%DEF(1,3),G%DEF(1,5),G%DEF(1,4),
     . G%DEF(1,6),G%DEF(1,7),G%DEF(1,8),M%GEO,PID,M%NU,M%SHF,
     . H%STRA,M%SSP,M%RHO,EPSDOT,0,1,2,
     . G%U(1,1,1),G%U(1,1,2),G%U(1,1,3),
     . G%U(1,2,1),G%U(1,2,2),G%U(1,2,3),
     . G%D(1,1),G%D(1,2),G%D(1,3),44,F_DEF,G%WXY,GSTRW,1)
      STATUS=2
      IF(GSTRW(1)/=17.25D0) RETURN
      EXX=G%DEF(1,1)
      EYY=G%DEF(1,2)
      EXY=G%DEF(1,3)
      KXX=G%DEF(1,6)
      KYY=G%DEF(1,7)
      KXY=G%DEF(1,8)
      GBUF%THK=H%THK(1)
      GBUF%EPSD=H%EPSD
      DT1C=STEP
#include "extracted/CallerRate.inc"
      H%EPSD=GBUF%EPSD(1)
! MULAWC centered one-point placement: true z=0 and thickness weight=1.
      ZPOSITION=ZERO*M%THK0(1)
      DO I=1,3
        DEPS(I)=G%DEF(1,I)+ZPOSITION*G%DEF(1,I+5)
      ENDDO
      DEPS(4:5)=G%DEF(1,4:5)
      CALL MembranePoint(MFUNC,NPTS,CURVE,BASIC,LINEAR,CONTROLS,ISRATE,D1,
     . STEP,TIME,DEPS,H%EPSD,M%GS(1),M%THK0(1),G%AREA(1:1),OLD_OFF,
     . POINT,FAILED,VALUES,WPLA)
! SOUNDSP is an actual SIGEPS44C result. Never replace it with pre-law PM27.
      M%SSP(1)=VALUES(11)
      FLAGS=INT(FAILED(3))
      WEIGHTS=ONE
      PARENT=OLD_OFF
      CALL ONE_POINT_PARENT(FLAGS,WEIGHTS,PARENT)
      CALL MembraneForceWork(1,G%DEF(1,:),M%THK0(1:1),G%AREA(1:1),M%DM,
     . STEP,M%SSP(1:1),M%RHO(1:1),OLD_OFF,PARENT,VALUES,
     . H%FOR,H%MOM,H%THK(1:1),H%EINT)
      H%FOR_G(1,:)=VALUES(1:5)*PARENT
      H%ACTIVE=PARENT
      G%OFF=PARENT
      VISCMX=ZERO
      VISCMX(1)=MAX(VISCMX(1),M%DM)
      CALL ONE_POINT_STIFFNESS(G,M,VISCMX,DTEL)
      CALL ONE_POINT_PROJECT(G,M,H,FORCE,COUPLE)
      CALL T3_PACK_HISTORY(H,STATE(1:26))
      STATE(27:33)=POINT
      STATE(34:36)=FAILED
      STATE(37)=WPLA
      OUTPUT(39:75)=STATE
      DO J=1,3
        K=76+3*(J-1)
        OUTPUT(K:K+2)=FORCE(1,:,J)
        K=85+3*(J-1)
        OUTPUT(K:K+2)=COUPLE(1,:,J)
      ENDDO
      OUTPUT(94:103)=[M%THK0(1),M%SSP(1),M%DM,M%SHF(1),M%GS(1),
     . M%STI(1),M%STIR(1),DTEL(1),H%EINT(1,1)-OLD_EINT(1),H%EINT(1,2)-OLD_EINT(2)]
      OUTPUT(104:116)=VALUES
      OUTPUT(117:124)=G%DEF(1,:)
      OUTPUT(125)=WPLA-OLD_WPLA
      OUTPUT(126)=ZERO
      IF(OLD_OFF==ONE.AND.PARENT==ZERO) OUTPUT(126)=ONE
      STATUS=0
      END
