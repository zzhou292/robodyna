      SUBROUTINE T3_R2_KINEMATICS(X,V,VR,STEP,OUTPUT,STATUS)
     . BIND(C,NAME="t3_r2_kinematics")
      USE ISO_C_BINDING, ONLY: C_DOUBLE,C_INT
      USE T3_ENGINE_GEOMETRY_MOD, ONLY: T3_GEOMETRY_,
     . T3_PREPARE_GEOMETRY,T3_PACK_GEOMETRY
      IMPLICIT NONE
      REAL(C_DOUBLE), INTENT(IN) :: X(3,3),V(3,3),VR(3,3),STEP
      REAL(C_DOUBLE), INTENT(OUT) :: OUTPUT(38)
      INTEGER(C_INT), INTENT(OUT) :: STATUS
      TYPE(T3_GEOMETRY_) G
      CALL T3_PREPARE_GEOMETRY(X,V,VR,STEP,G,STATUS)
      IF(STATUS/=0) RETURN
      CALL T3_PACK_GEOMETRY(G,OUTPUT)
      END
