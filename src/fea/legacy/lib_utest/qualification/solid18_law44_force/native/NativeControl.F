      SUBROUTINE REAR18_FORCE_CONTROL(G,NODES,DSV,RAW,DEG)
      USE SOLID18_FORCE_PACKETS
      USE SOLID18_REF_ELEMENT_MOD, ONLY:NIXS
#include "implicit_f.inc"
      TYPE(NATIVE_GEOMETRY),INTENT(IN) :: G
      INTEGER,INTENT(IN) :: NODES(8)
      REAL(KIND=8),INTENT(OUT) :: DSV(1)
      INTEGER,INTENT(OUT) :: RAW,DEG
      INTEGER IXS(NIXS,1),IDEG(1),I
      IXS=0
      IXS(2:9,1)=NODES
      CALL REAR18_FORCE_DEGENES8(IXS,IDEG,1)
      RAW=IDEG(1)
      I=1
#include "degeneracy_call.inc"
      DEG=IDEG(1)
      CALL REAR18_FORCE_S8EDEFOC3(
     . G%CENTER_P(1,1,1),G%CENTER_P(1,2,1),G%CENTER_P(1,3,1),G%CENTER_P(1,4,1),
     . G%CENTER_P(1,1,2),G%CENTER_P(1,2,2),G%CENTER_P(1,3,2),G%CENTER_P(1,4,2),
     . G%CENTER_P(1,1,3),G%CENTER_P(1,2,3),G%CENTER_P(1,3,3),G%CENTER_P(1,4,3),
     . G%V(1,1,1),G%V(1,2,1),G%V(1,3,1),G%V(1,4,1),
     . G%V(1,5,1),G%V(1,6,1),G%V(1,7,1),G%V(1,8,1),
     . G%V(1,1,2),G%V(1,2,2),G%V(1,3,2),G%V(1,4,2),
     . G%V(1,5,2),G%V(1,6,2),G%V(1,7,2),G%V(1,8,2),
     . G%V(1,1,3),G%V(1,2,3),G%V(1,3,3),G%V(1,4,3),
     . G%V(1,5,3),G%V(1,6,3),G%V(1,7,3),G%V(1,8,3),
     . DSV,1)
      END

      SUBROUTINE REAR18_FORCE_PRESSURE(G,PP,DEG,FORCE)
      USE SOLID18_FORCE_PACKETS
#include "implicit_f.inc"
      TYPE(NATIVE_GEOMETRY),INTENT(IN) :: G
      REAL(KIND=8),INTENT(IN) :: PP(1)
      INTEGER,INTENT(IN) :: DEG
      REAL(KIND=8),INTENT(INOUT) :: FORCE(MVSIZ,8,3)
      INTEGER IDEG(1)
      IDEG=DEG
      CALL REAR18_FORCE_S8ZFINTP3(
     . G%CENTER_P(1,1,1),G%CENTER_P(1,2,1),G%CENTER_P(1,3,1),G%CENTER_P(1,4,1),
     . G%CENTER_P(1,1,2),G%CENTER_P(1,2,2),G%CENTER_P(1,3,2),G%CENTER_P(1,4,2),
     . G%CENTER_P(1,1,3),G%CENTER_P(1,2,3),G%CENTER_P(1,3,3),G%CENTER_P(1,4,3),
     . FORCE(1,1,1),FORCE(1,1,2),FORCE(1,1,3),FORCE(1,2,1),
     . FORCE(1,2,2),FORCE(1,2,3),FORCE(1,3,1),FORCE(1,3,2),
     . FORCE(1,3,3),FORCE(1,4,1),FORCE(1,4,2),FORCE(1,4,3),
     . FORCE(1,5,1),FORCE(1,5,2),FORCE(1,5,3),FORCE(1,6,1),
     . FORCE(1,6,2),FORCE(1,6,3),FORCE(1,7,1),FORCE(1,7,2),
     . FORCE(1,7,3),FORCE(1,8,1),FORCE(1,8,2),FORCE(1,8,3),
     . G%CENTER_VOLUME,PP,IDEG,1)
      END
