! Caller-owned native state is input/output; no production evaluator is called.
      SUBROUTINE SOLID18_FORCE_NATIVE(NPTS,CURVE,E,NU,RHO,BASE,GLOBAL,
     . SAVED,VOLUME0,X,V,BASE_TIME,STEP_DT,NOW,NEXTGLOBAL,NEXTSAVED,
     . OBS,FORCES,GEOMETRY,DIAGNOSTICS,STATUS)
     . BIND(C,NAME="solid18_force_native")
      USE ISO_C_BINDING,ONLY:C_INT,C_DOUBLE
      USE SOLID18_FORCE_PACKETS
#include "implicit_f.inc"
      INTEGER(C_INT),INTENT(IN) :: NPTS
      REAL(C_DOUBLE),INTENT(IN) :: CURVE(2,NPTS+1),E,NU,RHO
      REAL(C_DOUBLE),INTENT(IN) :: BASE(20,8),GLOBAL(11),SAVED(21),VOLUME0
      REAL(C_DOUBLE),INTENT(IN) :: X(3,8),V(3,8),BASE_TIME,STEP_DT
      REAL(C_DOUBLE),INTENT(OUT) :: NOW(20,8),NEXTGLOBAL(11),NEXTSAVED(21)
      REAL(C_DOUBLE),INTENT(OUT) :: OBS(38,8),FORCES(3,8),GEOMETRY(1111),DIAGNOSTICS(7)
      INTEGER(C_INT),INTENT(OUT) :: STATUS
      TYPE(NATIVE_GEOMETRY),ALLOCATABLE :: G
      REAL(C_DOUBLE) :: UPARAM(31),FACTOR,POISSON,LENGTH,LOCAL_FORCE(MVSIZ,8,3)
      REAL(C_DOUBLE) :: TRIAL(20,8),GTRIAL(11),OTRIAL(38,8),DTRIAL(7)
      INTEGER IR,IS,IT,IP,N,K,J,POS,SELECTED
      ALLOCATE(G)
      CALL LAW36_NATIVE_SETUP(E,NU,RHO,0,UPARAM)
      CALL SOLID18_FORCE_SELECT(BASE,GLOBAL,UPARAM,FACTOR,POISSON,SELECTED)
      CALL SOLID18_FORCE_GEOMETRY(X,V,SAVED,POISSON,G,STATUS)
      IF(STATUS/=0) RETURN
      LOCAL_FORCE=ZERO
      GTRIAL=ZERO
      DTRIAL=ZERO
      DTRIAL(1)=FACTOR
      DTRIAL(2)=POISSON
      DTRIAL(3)=SELECTED
      DTRIAL(4)=EP30
      LENGTH=EP30
      DO IR=1,2
       DO IS=1,2
        DO IT=1,2
         IP=IR+((IS-1)+(IT-1)*2)*2
         CALL SOLID18_FORCE_POINT(G,IP,BASE(:,IP),NPTS,CURVE,E,NU,RHO,
     .    BASE_TIME,STEP_DT,LENGTH,TRIAL(:,IP),OTRIAL(:,IP),LOCAL_FORCE)
         CALL SOLID18_FORCE_REDUCE(G,IP,TRIAL(:,IP),OTRIAL(:,IP),
     .    VOLUME0,GTRIAL,DTRIAL(5))
         DTRIAL(4)=MIN(DTRIAL(4),OTRIAL(37,IP))
         DTRIAL(6)=DTRIAL(6)+OTRIAL(23,IP)
         DTRIAL(7)=DTRIAL(7)+OTRIAL(24,IP)
        END DO
       END DO
      END DO
      CALL SOLID18_FORCE_SRROTA3(
     . G%FRAME(1,1),G%FRAME(1,4),G%FRAME(1,7),G%FRAME(1,2),
     . G%FRAME(1,5),G%FRAME(1,8),G%FRAME(1,3),G%FRAME(1,6),
     . G%FRAME(1,9),LOCAL_FORCE(1,1,1),LOCAL_FORCE(1,2,1),LOCAL_FORCE(1,3,1),
     . LOCAL_FORCE(1,4,1),LOCAL_FORCE(1,5,1),LOCAL_FORCE(1,6,1),LOCAL_FORCE(1,7,1),
     . LOCAL_FORCE(1,8,1),LOCAL_FORCE(1,1,2),LOCAL_FORCE(1,2,2),LOCAL_FORCE(1,3,2),
     . LOCAL_FORCE(1,4,2),LOCAL_FORCE(1,5,2),LOCAL_FORCE(1,6,2),LOCAL_FORCE(1,7,2),
     . LOCAL_FORCE(1,8,2),LOCAL_FORCE(1,1,3),LOCAL_FORCE(1,2,3),LOCAL_FORCE(1,3,3),
     . LOCAL_FORCE(1,4,3),LOCAL_FORCE(1,5,3),LOCAL_FORCE(1,6,3),LOCAL_FORCE(1,7,3),
     . LOCAL_FORCE(1,8,3),1)
      NOW=TRIAL
      NEXTGLOBAL=GTRIAL
      OBS=OTRIAL
      DIAGNOSTICS=DTRIAL
      DO N=1,8
       FORCES(:,N)=LOCAL_FORCE(1,N,:)
      END DO
      DO N=1,7
       NEXTSAVED(3*N-2:3*N)=G%X(1,N,:)-G%X(1,8,:)
      END DO
      POS=1
      GEOMETRY(POS:POS+8)=G%FRAME(1,:)
      POS=POS+9
      DO N=1,8
       GEOMETRY(POS:POS+2)=G%X(1,N,:)
       POS=POS+3
      END DO
      DO N=1,8
       GEOMETRY(POS:POS+2)=G%V(1,N,:)
       POS=POS+3
      END DO
      DO K=1,3
       GEOMETRY(POS:POS+3)=G%CENTER_P(1,:,K)
       POS=POS+4
      END DO
      GEOMETRY(POS)=G%CENTER_VOLUME(1)
      GEOMETRY(POS+1)=G%SMAX(1)
      POS=POS+2
      DO IP=1,8
       DO K=1,3
        GEOMETRY(POS:POS+7)=G%P(1,IP,:,K)
        POS=POS+8
       END DO
       DO K=1,6
        GEOMETRY(POS:POS+7)=G%SHEAR(1,IP,:,K)
        POS=POS+8
       END DO
       DO K=1,6
        GEOMETRY(POS:POS+7)=G%CROSS(1,IP,:,K)
        POS=POS+8
       END DO
       GEOMETRY(POS:POS+8)=G%INVERSE(1,IP,:)
       POS=POS+9
       GEOMETRY(POS)=G%VOLUME(1,IP)
       POS=POS+1
      END DO
      IF(POS/=1112) ERROR STOP 'Native geometry packet shape'
      END
