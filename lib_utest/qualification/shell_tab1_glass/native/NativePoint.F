! Complete original TAB1 point and weighted table calls; no production math.
      MODULE TAB1_POINT_BRIDGE
      USE ISO_C_BINDING,ONLY:C_DOUBLE,C_INT
      USE GLASS_TAB1_TABLE_MOD
      USE GLASS_TAB1_INTERFACE_TABLE_MOD
      IMPLICIT NONE
      INTERFACE
        SUBROUTINE TAB1_NATIVE_DEFAULTS(PARAMETERS,THRESHOLD)
     .  BIND(C,NAME='tab1_native_defaults')
          IMPORT C_DOUBLE
          REAL(C_DOUBLE),INTENT(OUT)::PARAMETERS(22),THRESHOLD
        END SUBROUTINE
      END INTERFACE
      CONTAINS
      SUBROUTINE TAB1_NATIVE_POINT(X,FAILURE_STRAIN,BASE,ELEMENT,DPLA,TIME,STRESS,VALUES)
     . BIND(C,NAME='tab1_native_point')
#include "implicit_f.inc"
#include "units_c.inc"
      REAL(C_DOUBLE),INTENT(IN)::X(3),BASE(5),STRESS(5)
      REAL(C_DOUBLE),VALUE::FAILURE_STRAIN,DPLA,TIME
      INTEGER(C_INT),VALUE::ELEMENT
      REAL(C_DOUBLE),INTENT(OUT)::VALUES(6)
      TYPE(TTABLE)::TABLE(1)
      TYPE(TTABLE_XY),TARGET::TX(1),TY
      MY_REAL,TARGET::XX(3),YY(3)
      MY_REAL UPARAM(22),UVAR(1,8),OFF(1),DFMAX(1),TDEL(1),DMG_SCALE(1),
     . DPLAS(1),EPSP(1),THK(1),ALDT(1),TEMP(1),SXX(1),SYY(1),SXY(1),TF(2),THRESHOLD
      INTEGER NGL(1),FOFF(1),ITABLF(2),IFUNC(4),NPF(2),DMG_FLAG
      CALL TAB1_NATIVE_DEFAULTS(UPARAM,THRESHOLD)
      XX=X
      YY=FAILURE_STRAIN
      TX(1)%VALUES=>XX
      TY%VALUES=>YY
      TABLE(1)%NOTABLE=17
      TABLE(1)%NDIM=1
      TABLE(1)%X=>TX
      TABLE(1)%Y=>TY
      UVAR=ZERO
      UVAR(1,1)=BASE(1)
! Finite auxiliary initial geometry is irrelevant to this no-thinning/no-size
! branch; do not label it a source startup or full native restart packet.
      UVAR(1,2)=ONE
      UVAR(1,5)=ONE
      UVAR(1,6)=BASE(5)
      DFMAX=BASE(4)
      FOFF=INT(BASE(3))
      OFF=DBLE(ELEMENT)
      DPLAS=DPLA
      EPSP=ZERO
      THK=ONE
      ALDT=ONE
      TEMP=ZERO
      SXX=STRESS(1)
      SYY=STRESS(2)
      SXY=STRESS(3)
      ITABLF=[1,0]
      IFUNC=0
      NPF=0
      TF=ZERO
      NGL=17
      IOUT=6
      ISTDO=6
      CALL GLASS_TAB1_FAIL_TAB_C(1,22,8,UPARAM,UVAR,4,IFUNC,TABLE,NPF,TF,
     . TIME,NGL,1,1,1,SXX,SYY,SXY,2,ITABLF,DPLAS,EPSP,THK,ALDT,TEMP,
     . DMG_FLAG,DMG_SCALE,OFF,FOFF,DFMAX,TDEL,0)
      VALUES(1)=UVAR(1,1)
      VALUES(2)=BASE(2)
! TDEL is INTENT(OUT), assigned only on failure. Never read an undefined value.
      IF(INT(BASE(3))==1.AND.FOFF(1)==0) VALUES(2)=TDEL(1)
      VALUES(3)=DBLE(FOFF(1))
      VALUES(4)=DFMAX(1)
      VALUES(5)=UVAR(1,6)
      VALUES(6)=DBLE(DMG_FLAG)
      END SUBROUTINE

      SUBROUTINE TAB1_NATIVE_TABLE(X,FAILURE_STRAIN,PROBE,CACHE,VALUE,DERIVATIVE,NEXT)
     . BIND(C,NAME='tab1_native_table')
      REAL(C_DOUBLE),INTENT(IN)::X(3)
      REAL(C_DOUBLE),VALUE::FAILURE_STRAIN,PROBE
      INTEGER(C_INT),VALUE::CACHE
      REAL(C_DOUBLE),INTENT(OUT)::VALUE,DERIVATIVE
      INTEGER(C_INT),INTENT(OUT)::NEXT
      TYPE(TTABLE)::TABLE
      TYPE(TTABLE_XY),TARGET::TX(1),TY
      REAL(C_DOUBLE),TARGET::XX(3),YY(3)
      REAL(C_DOUBLE)::QUERY(1,1),RESULT(1),SLOPE(1)
      INTEGER::IPOS(1,1)
      XX=X
      YY=FAILURE_STRAIN
      TX(1)%VALUES=>XX
      TY%VALUES=>YY
      TABLE%NOTABLE=17
      TABLE%NDIM=1
      TABLE%X=>TX
      TABLE%Y=>TY
      QUERY=PROBE
      IPOS=CACHE
      CALL GLASS_TAB1_TABLE_VINTERP(TABLE,1,1,IPOS,QUERY,RESULT,SLOPE)
      VALUE=RESULT(1)
      DERIVATIVE=SLOPE(1)
      NEXT=IPOS(1,1)
      END SUBROUTINE
      END MODULE
