! Ordinary ABI retains its positive-duration guard over shared arithmetic.
      SUBROUTINE REAR18_FORCE_NATIVE(NPTS,CURVE,MATERIAL,UNITS,NODES,
     . BASE,CURSORS,GLOBAL,SAVED,VOLUME0,X,V,BASE_TIME,STEP_DT,
     . NOW,NEXTCURSOR,NEXTGLOBAL,NEXTSAVED,OBS,FORCES,GEOMETRY,DIAGNOSTICS,STATUS)
     . BIND(C,NAME="rear18_force_native")
      USE REAR18_FORCE_ENTRY_INTERFACE
      IMPLICIT NONE
      INTEGER(C_INT),INTENT(IN) :: NPTS,UNITS,NODES(8),CURSORS(8)
      REAL(C_DOUBLE),INTENT(IN) :: CURVE(2,NPTS+1),MATERIAL(7)
      REAL(C_DOUBLE),INTENT(IN) :: BASE(20,8),GLOBAL(12),SAVED(21),VOLUME0
      REAL(C_DOUBLE),INTENT(IN) :: X(3,8),V(3,8),BASE_TIME,STEP_DT
      REAL(C_DOUBLE),INTENT(OUT) :: NOW(20,8),NEXTGLOBAL(12),NEXTSAVED(21)
      REAL(C_DOUBLE),INTENT(OUT) :: OBS(38,8),FORCES(3,8),GEOMETRY(1111),DIAGNOSTICS(8)
      INTEGER(C_INT),INTENT(OUT) :: NEXTCURSOR(8),STATUS
      STATUS=1
      IF(STEP_DT<=0D0) RETURN
      CALL REAR18_FORCE_CALCULATE(NPTS,CURVE,MATERIAL,UNITS,NODES,
     . BASE,CURSORS,GLOBAL,SAVED,VOLUME0,X,V,BASE_TIME,STEP_DT,
     . NOW,NEXTCURSOR,NEXTGLOBAL,NEXTSAVED,OBS,FORCES,GEOMETRY,DIAGNOSTICS,STATUS)
      END

! Reference inputs are independently prepared native startup fields. This entry
! accepts no prior material/history/cursor/time and constructs virgin state.
      SUBROUTINE REAR18_FORCE_INITIAL(NPTS,CURVE,MATERIAL,UNITS,NODES,
     . VOLUMES,VOLUME0,DENSITY0,SAVED,XREF,VELOCITY,
     . NOW,NEXTCURSOR,NEXTGLOBAL,NEXTSAVED,OBS,FORCES,GEOMETRY,DIAGNOSTICS,STATUS)
     . BIND(C,NAME="rear18_force_initial_native")
      USE REAR18_FORCE_ENTRY_INTERFACE
      USE IEEE_ARITHMETIC,ONLY:IEEE_IS_FINITE
#include "implicit_f.inc"
#include "com08_c.inc"
      INTEGER(C_INT),INTENT(IN) :: NPTS,UNITS,NODES(8)
      REAL(C_DOUBLE),INTENT(IN) :: CURVE(2,NPTS+1),MATERIAL(7)
      REAL(C_DOUBLE),INTENT(IN) :: VOLUMES(8),VOLUME0,DENSITY0,SAVED(21)
      REAL(C_DOUBLE),INTENT(IN) :: XREF(3,8),VELOCITY(3)
      REAL(C_DOUBLE),INTENT(OUT) :: NOW(20,8),NEXTGLOBAL(12),NEXTSAVED(21)
      REAL(C_DOUBLE),INTENT(OUT) :: OBS(38,8),FORCES(3,8),GEOMETRY(1111),DIAGNOSTICS(8)
      INTEGER(C_INT),INTENT(OUT) :: NEXTCURSOR(8),STATUS
      REAL(C_DOUBLE) :: BASE(20,8),GLOBAL(12),V(3,8)
      INTEGER(C_INT) :: CURSORS(8)
      INTEGER N
      STATUS=1
      IF(.NOT.ALL(IEEE_IS_FINITE(VELOCITY))) RETURN
      BASE=ZERO
      GLOBAL=ZERO
      CURSORS=0
      BASE(17,:)=MATERIAL(3)
      BASE(18,:)=VOLUMES
      BASE(19,:)=VOLUMES
      GLOBAL(8)=DENSITY0
      DO N=1,8
       V(:,N)=VELOCITY
      ENDDO
      TT=ZERO
      DT1=ZERO
      DT2=ZERO
      CALL REAR18_FORCE_CALCULATE(NPTS,CURVE,MATERIAL,UNITS,NODES,
     . BASE,CURSORS,GLOBAL,SAVED,VOLUME0,XREF,V,ZERO,ZERO,
     . NOW,NEXTCURSOR,NEXTGLOBAL,NEXTSAVED,OBS,FORCES,GEOMETRY,DIAGNOSTICS,STATUS)
      END
