      SUBROUTINE IC1_ASSEMBLE(F,STI,ASSEMBLED,NODAL)
      USE HEPH_NATIVE_PACKETS
      USE IC1_NATIVE_INTERFACES
      IMPLICIT NONE
      REAL(KIND=8),INTENT(INOUT)::F(MVSIZ,8,3),STI(MVSIZ)
      REAL(KIND=8),INTENT(OUT)::ASSEMBLED(3,8),NODAL(8)
      REAL(KIND=8)::OFF(1),AR(3,8),DUMMY(MVSIZ),THEM(MVSIZ,8)
      INTEGER::NODES(1,8),N
      OFF=ONE
      ASSEMBLED=ZERO
      NODAL=ZERO
      AR=ZERO
      DUMMY=ZERO
      THEM=ZERO
      DO N=1,8
        NODES(1,N)=N
      ENDDO
      CALL IC1_NATIVE_SCUMU3(
     . OFF,ASSEMBLED,NODES(1,1),NODES(1,2),
     . NODES(1,3),NODES(1,4),NODES(1,5),NODES(1,6),
     . NODES(1,7),NODES(1,8),NODAL,STI,
     . F(1,1,1),F(1,1,2),F(1,1,3),F(1,2,1),
     . F(1,2,2),F(1,2,3),F(1,3,1),F(1,3,2),
     . F(1,3,3),F(1,4,1),F(1,4,2),F(1,4,3),
     . F(1,5,1),F(1,5,2),F(1,5,3),F(1,6,1),
     . F(1,6,2),F(1,6,3),F(1,7,1),F(1,7,2),
     . F(1,7,3),F(1,8,1),F(1,8,2),F(1,8,3),
     . 0,AR,DUMMY,DUMMY,
     . DUMMY,DUMMY,DUMMY,DUMMY,
     . DUMMY,DUMMY,DUMMY,DUMMY,
     . DUMMY,DUMMY,DUMMY,DUMMY,
     . DUMMY,DUMMY,DUMMY,DUMMY,
     . DUMMY,DUMMY,DUMMY,DUMMY,
     . DUMMY,DUMMY,DUMMY,DUMMY,
     . THEM,DUMMY,DUMMY,DUMMY,
     . 1,0,0,0,
     . 0)
      END
