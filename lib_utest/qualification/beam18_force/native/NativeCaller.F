      SUBROUTINE BEAM18_FORCE_NATIVE(REFERENCE,RAW,NPTS,CURVE,
     . BASE,CURSOR,X,V,R,BASE_TIME,H,INITIAL,VALUES,NEXT_CURSOR,STATUS)
     . BIND(C,NAME="beam18_force_native")
      USE ISO_C_BINDING,ONLY:C_DOUBLE,C_INT
      USE LAW44_SOLID_SETUP,ONLY:PREPARE_LAW44
      USE B18F_ELBUFDEF_MOD
      USE B18F_MATPARAM_DEF_MOD
#include "implicit_f.inc"
#include "param_c.inc"
#include "com04_c.inc"
#include "com08_c.inc"
#include "impl1_c.inc"
#include "vect01_c.inc"
#include "scr02_c.inc"
#include "scr17_c.inc"
      INTEGER(C_INT),VALUE :: NPTS,INITIAL
      REAL(C_DOUBLE),INTENT(IN) :: REFERENCE(27),RAW(7),CURVE(2,NPTS+1)
      REAL(C_DOUBLE),INTENT(IN) :: BASE(41),X(3,2),V(3,2),R(3,2),BASE_TIME,H
      INTEGER(C_INT),INTENT(IN) :: CURSOR(4)
      REAL(C_DOUBLE),INTENT(OUT) :: VALUES(85)
      INTEGER(C_INT),INTENT(OUT) :: NEXT_CURSOR(4),STATUS
      REAL(C_DOUBLE) GEO(NPROPG,1),PM(NPROPM,1),UPARAM(24),OMEGA
      REAL(C_DOUBLE) OFFG(1),OFF(1),AL(1),TL(1),MSP(1),DMELP(1),DTEL(1),DT2T
      REAL(C_DOUBLE) RLOC(3,1),RX1G(1),RX2G(1),RY1G(1),RY2G(1),RZ1G(1),RZ2G(1)
      REAL(C_DOUBLE) E1X(1),E1Y(1),E1Z(1),E2X(1),E2Y(1),E2Z(1),E3X(1),E3Y(1),E3Z(1)
      REAL(C_DOUBLE) VX1G(1),VX2G(1),VY1G(1),VY2G(1),VZ1G(1),VZ2G(1)
      REAL(C_DOUBLE) EXX(1),EXY(1),EXZ(1),KXX(1),KYY(1),KZZ(1),RATES(6)
      REAL(C_DOUBLE) FOR(1,3),MOM(1,3),EINT(1,2),EPSD(1),TEMPEL(1)
      REAL(C_DOUBLE) F1(1),F2(1),F3(1),M1(1),M2(1),M3(1),STI(1),STIR(1)
      REAL(C_DOUBLE) F11(1),F12(1),F21(1),F22(1),F31(1),F32(1)
      REAL(C_DOUBLE) M11(1),M12(1),M21(1),M22(1),M31(1),M32(1)
      REAL(C_DOUBLE) FX1(1),FX2(1),FY1(1),FY2(1),FZ1(1),FZ2(1)
      REAL(C_DOUBLE) MX1(1),MX2(1),MY1(1),MY2(1),MZ1(1),MZ2(1)
      REAL(C_DOUBLE) F(3,3),M(3,3),STIFN(3),STIFR(3),FPHI(1,2),FTHE(3)
      REAL(C_DOUBLE),TARGET :: SIG(3,4),STRA(3,4),PLA(1,4),UVAR(1,4),UNUSED(3,4),WPLA(1)
      INTEGER,TARGET :: VARTMP(1,4)
      TYPE(L_BUFEL_),TARGET :: POINTS(1,1,4)
      TYPE(MATBUF_),TARGET :: MATBUFFERS(1,1,4)
      TYPE(BUF_LAY_),TARGET :: LAYERS(1)
      TYPE(G_BUFEL_),TARGET :: GLOBAL
      TYPE(ELBUF_STRUCT_),TARGET :: ELBUF
      TYPE(MATPARAM_STRUCT_) MATPARAM
      TYPE(TTABLE) TABLE(1)
      INTEGER IPM(NPROPMI,1),NPF(2),PID(1),MAT(1),NGL(1),NC1(1),NC2(1),NC3(1)
      INTEGER I,J,K,IREL(6,1),NELTST,ITYPTST
      STATUS=1
      VALUES=ZERO
      NEXT_CURSOR=-1
      IF(NPTS<2.OR.NPTS>1024.OR.INITIAL<0.OR.INITIAL>1) RETURN
      IF(H<ZERO.OR.(INITIAL==0.AND.H<=ZERO)) RETURN
      IF(INITIAL==1.AND.(H/=ZERO.OR.BASE_TIME/=ZERO)) RETURN
      IF(ANY(CURSOR<0).OR.ANY(CURSOR>=NPTS-1)) RETURN
      CALL PREPARE_LAW44(RAW,UPARAM,OMEGA)
      GEO=ZERO
      DO J=1,4
        GEO(200+J,1)=REFERENCE(3*J-2)
        GEO(300+J,1)=REFERENCE(3*J-1)
        GEO(400+J,1)=REFERENCE(3*J)
      ENDDO
      GEO(1,1)=REFERENCE(13)
      GEO(2,1)=REFERENCE(14)
      GEO(18,1)=REFERENCE(15)
      GEO(4,1)=REFERENCE(16)
      GEO(7:11,1)=ONE
      GEO(16,1)=REFERENCE(26)
      GEO(17,1)=REFERENCE(27)
      GEO(90,1)=ONE
      PM=ZERO
      PM(1,1)=RAW(3)
      PM(20,1)=RAW(1)
      PM(22,1)=UPARAM(16)
      PM(27,1)=SQRT(UPARAM(20)/RAW(3))
      PM(9,1)=OMEGA
      IPM=0
      IPM(3,1)=1
      IPM(7,1)=1
      IPM(9,1)=24
      IPM(10,1)=1
      IPM(11,1)=1
      NPF=(/0,2*(NPTS+1)/)
      PID=1
      MAT=1
      NGL=101
      NC1=1
      NC2=2
      NC3=2
      LFT=1
      LLT=1
      CALL B18F_PIBUF3(GEO,OFFG,TL,REFERENCE(17:17),PID,IREL)
      DO J=1,4
        SIG(:,J)=BASE(7*J-6:7*J-4)
        STRA(:,J)=BASE(7*J-3:7*J-1)
        PLA(1,J)=BASE(7*J)
        VARTMP(1,J)=CURSOR(J)+1
        POINTS(1,1,J)%SIG=>SIG(:,J)
        POINTS(1,1,J)%STRA=>STRA(:,J)
        POINTS(1,1,J)%PLA=>PLA(:,J)
        POINTS(1,1,J)%DMGSCL=>UNUSED(1:1,J)
        POINTS(1,1,J)%FRAC=>UNUSED(1:1,J)
        POINTS(1,1,J)%SIGB=>UNUSED(:,J)
        POINTS(1,1,J)%SEQ=>UNUSED(1:1,J)
        MATBUFFERS(1,1,J)%VAR=>UVAR(:,J)
        MATBUFFERS(1,1,J)%VARTMP=>VARTMP(:,J)
      ENDDO
      UVAR=ZERO
      UNUSED=ZERO
      RLOC(:,1)=BASE(29:31)
      FOR(1,:)=BASE(32:34)
      MOM(1,:)=BASE(35:37)
      EPSD=BASE(38)
      EINT(1,:)=BASE(39:40)
      WPLA=BASE(41)
      IF(INITIAL==1) THEN
        SIG=ZERO
        STRA=ZERO
        PLA=ZERO
        VARTMP=1
        RLOC(:,1)=REFERENCE(18:20)
        FOR=ZERO
        MOM=ZERO
        EPSD=ZERO
        EINT=ZERO
        WPLA=ZERO
      ENDIF
      LAYERS(1)%LBUF=>POINTS
      LAYERS(1)%MAT=>MATBUFFERS
      ELBUF%BUFLY=>LAYERS
      ELBUF%GBUF=>GLOBAL
      GLOBAL%WPLA=>WPLA
      GLOBAL%MAXFRAC=>UNUSED(1:1,1)
      GLOBAL%MAXEPS=>UNUSED(:,1)
      TT=BASE_TIME+H
      DT1=H
      DT2=H
      IMPL_S=0
      ISMDISP=0
      IOUT=6
      ISTDO=6
      IDTMINS=0
      NODADT=1
      IDTMIN=0
      IDTMIN(5)=1
      DTMINS=ZERO
      DTFACS=ONE
      DTFAC1=ONE
      DTMIN1=ZERO
      TSTOP=ZERO
      IDEL7NOK=0
      MSTOP=0
      TEMPEL=ZERO
      MSP=REFERENCE(21)
      DMELP=ZERO
      DTEL=-ONE
      DT2T=INFINITY
      NELTST=0
      ITYPTST=0
      CALL B18F_PEVEC3(RLOC,R,AL,NC1,NC2,NC3,
     . X(1,1:1),X(1,2:2),X(1,2:2),X(2,1:1),X(2,2:2),X(2,2:2),
     . X(3,1:1),X(3,2:2),X(3,2:2),RX1G,RX2G,RY1G,RY2G,RZ1G,RZ2G,
     . E1X,E1Y,E1Z,E2X,E2Y,E2Z,E3X,E3Y,E3Z,1)
      CALL B18F_PDLEN3(1,1,PM,GEO,OFFG,DT2T,NELTST,ITYPTST,STI,STIR,
     . MSP,DMELP,1,DTEL,AL,MAT,PID,NGL,1,18,0)
      CALL B18F_PDEFO3(V,EXX,EXY,EXZ,AL,NC1,NC2,NC3,E1X,E1Y,E1Z,
     . E2X,E2Y,E2Z,E3X,E3Y,E3Z,VX1G,VX2G,VY1G,VY2G,VZ1G,VZ2G,1)
      CALL B18F_PCURV3(R,GEO,OFFG,OFF,EXX,EXY,EXZ,KXX,KYY,KZZ,AL,
     . NC1,NC2,NC3,RX1G,RX2G,RY1G,RY2G,RZ1G,RZ2G,E1X,E1Y,E1Z,
     . E2X,E2Y,E2Z,E3X,E3Y,E3Z,PID,1)
      RATES=(/EXX(1),EXY(1),EXZ(1),KXX(1),KYY(1),KZZ(1)/)
      CALL B18F_MAIN_BEAM18(ELBUF,1,4,44,1,PID,NGL,PM,IPM,GEO,OFF,
     . FOR,MOM,EINT,AL,EPSD,UPARAM,NPF,CURVE,EXX,EXY,EXZ,KXX,KYY,KZZ,
     . F1,F2,F3,M1,M2,M3,0,TEMPEL,0,24,2,2*(NPTS+1),1,1,6,6,
     . NPROPMI,NPROPM,NPROPG,TT,DT1,IDEL7NOK,0,0,0,MATPARAM,1,TABLE)
      CALL B18F_PDAMP3(PM,GEO,OFF,1,1,1,NGL,EXX,EXY,EXZ,KXX,KYY,KZZ,
     . AL,F1,F2,F3,M1,M2,M3,0,0,DT1)
      VALUES(73:78)=(/F1(1),F2(1),F3(1),M1(1),M2(1),M3(1)/)
      CALL B18F_PFINT3(FOR,MOM,GEO,OFFG,OFF,AL,F1,F2,F3,M1,M2,M3,STI,STIR,
     . 1,PID,F11,F12,F21,F22,F31,F32,M11,M12,M21,M22,M31,M32)
      F=ZERO
      M=ZERO
      STIFN=ZERO
      STIFR=ZERO
      FPHI=ZERO
      FTHE=ZERO
      CALL B18F_PFCUM3(F,STI,STIFN,FX1,FX2,FY1,FY2,FZ1,FZ2,NC1,NC2,NC3,
     . E1X,E1Y,E1Z,E2X,E2Y,E2Z,E3X,E3Y,E3Z,F11,F12,F21,F22,F31,F32,FPHI,FTHE,1,0)
      CALL B18F_PMCUM3(M,STIR,STIFR,MX1,MX2,MY1,MY2,MZ1,MZ2,NC1,NC2,NC3,
     . E1X,E1Y,E1Z,E2X,E2Y,E2Z,E3X,E3Y,E3Z,M11,M12,M21,M22,M31,M32,1)
      DO J=1,4
        VALUES(7*J-6:7*J-4)=SIG(:,J)
        VALUES(7*J-3:7*J-1)=STRA(:,J)
        VALUES(7*J)=PLA(1,J)
      ENDDO
      VALUES(29:31)=RLOC(:,1)
      VALUES(32:34)=FOR(1,:)
      VALUES(35:37)=MOM(1,:)
      VALUES(38)=EPSD(1)
      VALUES(39:40)=EINT(1,:)
      VALUES(41)=WPLA(1)
      VALUES(42:47)=RESHAPE(F(:,1:2),(/6/))
      VALUES(48:53)=RESHAPE(M(:,1:2),(/6/))
      VALUES(54:62)=(/E1X(1),E1Y(1),E1Z(1),E2X(1),E2Y(1),E2Z(1),E3X(1),E3Y(1),E3Z(1)/)
      VALUES(63)=AL(1)
      VALUES(64:69)=RATES
      VALUES(70)=STI(1)
      VALUES(71)=STIR(1)
! PDLEN3 returns before DTEL under NODADT; report its independently computed
! element monitor by a second unchanged call with NODADT0, preserving STI/STIR.
      NODADT=0
      CALL B18F_PDLEN3(1,1,PM,GEO,OFFG,DT2T,NELTST,ITYPTST,F1,M1,
     . MSP,DMELP,1,DTEL,AL,MAT,PID,NGL,1,18,0)
      VALUES(72)=DTEL(1)
      VALUES(79:81)=STIFN
      VALUES(82:84)=STIFR
      VALUES(85)=OFFG(1)
      NEXT_CURSOR=VARTMP(1,:)-1
      IF(OFFG(1)/=ONE.OR.IDEL7NOK/=0.OR.MSTOP/=0) RETURN
      STATUS=0
      END SUBROUTINE
