      SUBROUTINE LAW90_FORCE_WORLD(G,FORCE)
      USE LAW90_ENGINE_PACKETS
      IMPLICIT NONE
      TYPE(NATIVE_GEOMETRY),INTENT(IN) :: G
      REAL(KIND=8),INTENT(INOUT) :: FORCE(MVSIZ,8,3)
      CALL LAW90_FORCE_SRROTA3(
     . G%FRAME(1,1),G%FRAME(1,4),G%FRAME(1,7),G%FRAME(1,2),
     . G%FRAME(1,5),G%FRAME(1,8),G%FRAME(1,3),G%FRAME(1,6),
     . G%FRAME(1,9),FORCE(1,1,1),FORCE(1,2,1),FORCE(1,3,1),
     . FORCE(1,4,1),FORCE(1,5,1),FORCE(1,6,1),FORCE(1,7,1),
     . FORCE(1,8,1),FORCE(1,1,2),FORCE(1,2,2),FORCE(1,3,2),
     . FORCE(1,4,2),FORCE(1,5,2),FORCE(1,6,2),FORCE(1,7,2),
     . FORCE(1,8,2),FORCE(1,1,3),FORCE(1,2,3),FORCE(1,3,3),
     . FORCE(1,4,3),FORCE(1,5,3),FORCE(1,6,3),FORCE(1,7,3),
     . FORCE(1,8,3),1)
      END
