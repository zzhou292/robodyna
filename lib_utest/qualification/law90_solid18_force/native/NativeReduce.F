! Complete S8EFMOY3 with actual LAW90 EPSD channel; no PLA/WPLA allocation.
      SUBROUTINE LAW90_FORCE_REDUCE(G,IP,NOW,STORED,VOLUME0,STI,GLOBAL,STIFF)
      USE LAW90_ENGINE_PACKETS
      IMPLICIT NONE
      TYPE(NATIVE_GEOMETRY),INTENT(IN) :: G
      INTEGER,INTENT(IN) :: IP
      INTEGER TAGS(6)
      INTERFACE
       SUBROUTINE GET_TAGS(T) BIND(C,NAME="law90_force_tags")
        USE ISO_C_BINDING
        INTEGER(C_INT),INTENT(OUT) :: T(6)
       END SUBROUTINE
      END INTERFACE
      REAL(KIND=8),INTENT(IN) :: NOW(20),STORED,VOLUME0,STI
      REAL(KIND=8),INTENT(INOUT) :: GLOBAL(10),STIFF
      REAL(KIND=8) :: ZERO_ARRAY(MVSIZ),SVIS(MVSIZ,6),PP(1),PLA(1)
      REAL(KIND=8) :: EINTTHM(1),CONDEN(1),ABSENT(0)
      CALL GET_TAGS(TAGS)
      ZERO_ARRAY=ZERO
      SVIS=ZERO
      PP=ZERO
      PLA=ZERO
      EINTTHM=ZERO
      CONDEN=ZERO
      CALL LAW90_FORCE_S8EFMOY3(
     . NOW(11),G%VOLUME(1,IP),NOW(19),PP,
     . NOW(18),NOW(17),NOW(19),ZERO_ARRAY,
     . NOW(20),GLOBAL(10),GLOBAL(1),GLOBAL(8),
     . GLOBAL(7),GLOBAL(9),PLA,G%CENTER_VOLUME,
     . STI,STIFF,0,ONE,
     . STORED,VOLUME0,TAGS(1),TAGS(3),
     . ZERO_ARRAY,EINTTHM,0,1,
     . ZERO_ARRAY,CONDEN,SVIS,0,
     . ABSENT,ABSENT,TAGS(2))
      END
