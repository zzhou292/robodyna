C I2COR3 call seam: supplied independently qualified consumed shell thickness.
C Complete native I2TRIVOX and I2DST3 still enumerate/project/select all rows.
      SUBROUTINE I2COR3(X,IRECT,NSV,CAND_E,CAND_N,
     . GAPV,IGAP,GAP,FIRST,LAST,NINT,IXC,IXTG,THK_PART,IPARTC,
     . GEO,NOINT,IXS,IXS10,PM,THK,KNOD2ELS,KNOD2ELC,KNOD2ELTG,
     . NOD2ELS,NOD2ELC,NOD2ELTG,IGNORE,IXS16,IXS20,IPARTTG,
     . IGEO,DSEARCH,PM_STACK,IWORKSH,IX1,IX2,IX3,IX4,NSVG,
     . X1,X2,X3,X4,Y1,Y2,Y3,Y4,Z1,Z2,Z3,Z4,XI,YI,ZI,
     . GAPMIN,GAPMAX)
      USE CONSTANT_MOD
      USE BUCKET_PACKET_CONTEXT
      IMPLICIT NONE
#include "mvsiz_p.inc"
      INTEGER FIRST,LAST,IGAP,NINT,NOINT,IGNORE
      INTEGER IRECT(4,*),NSV(*),CAND_E(*),CAND_N(*),IXC(*),IXTG(*)
      INTEGER IPARTC(*),IXS(*),IXS10(*),KNOD2ELS(*),KNOD2ELC(*)
      INTEGER KNOD2ELTG(*),NOD2ELS(*),NOD2ELC(*),NOD2ELTG(*)
      INTEGER IXS16(*),IXS20(*),IPARTTG(*),IGEO(*),IWORKSH(*)
      INTEGER IX1(MVSIZ),IX2(MVSIZ),IX3(MVSIZ),IX4(MVSIZ),NSVG(MVSIZ)
      DOUBLE PRECISION X(3,*),GAPV(*),GAP,THK_PART(*),GEO(*),PM(*)
      DOUBLE PRECISION THK(*),DSEARCH,PM_STACK(*),GAPMIN,GAPMAX
      DOUBLE PRECISION X1(MVSIZ),X2(MVSIZ),X3(MVSIZ),X4(MVSIZ)
      DOUBLE PRECISION Y1(MVSIZ),Y2(MVSIZ),Y3(MVSIZ),Y4(MVSIZ)
      DOUBLE PRECISION Z1(MVSIZ),Z2(MVSIZ),Z3(MVSIZ),Z4(MVSIZ)
      DOUBLE PRECISION XI(MVSIZ),YI(MVSIZ),ZI(MVSIZ)
      INTEGER I,IG,L,NN,NODE1,NODE2,NODE3,NODE4
      DOUBLE PRECISION DD,DX1,DY1,DZ1,DX3,DY3,DZ3,THKSECND,THKMAIN
      IF(IGAP/=0.OR.IGNORE/=2.OR.DSEARCH/=ZERO)
     . ERROR STOP 'Unsupported native bucket coordinate profile'
      CALL RECORD_PAIRS(FIRST,LAST,CAND_E,CAND_N)
#include "SecondaryCoordinates.inc"
      DO I=FIRST,LAST
        THKSECND=ZERO
        THKMAIN=PROJECTION_THICKNESS(CAND_E(I))
#include "Gap.inc"
        GAPMIN=MIN(GAPMIN,GAPV(I))
        GAPMAX=MAX(GAPMAX,GAPV(I))
      ENDDO
#include "MasterCoordinates.inc"
      END

      SUBROUTINE I2DST3_27()
      ERROR STOP 'ILEV27 is outside the explicit native bucket profile'
      END
