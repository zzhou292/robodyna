! Exact LECINT count branch, with supplied source-order IGRNOD values.
      SUBROUTINE FIRST_CONNECTIONS(NN,NSN,NODES,IS1,
     . COUNTS,NSN_MULTI_CONNEC)
      IMPLICIT NONE
      INTEGER NN,NSN,NODES(NSN),IS1,COUNTS(NN),NSN_MULTI_CONNEC
      INTEGER I,ISL,ISU1
      TYPE NODE_GROUP
        INTEGER NENTITY
        INTEGER,ALLOCATABLE :: ENTITY(:)
      END TYPE
      TYPE(NODE_GROUP) IGRNOD(1)
      INTEGER,ALLOCATABLE :: T2_NB_CONNEC(:)
      ISU1=1
      IGRNOD(1)%NENTITY=NSN
      ALLOCATE(IGRNOD(1)%ENTITY(NSN),T2_NB_CONNEC(NN))
      IGRNOD(1)%ENTITY=NODES
      T2_NB_CONNEC=0
      NSN_MULTI_CONNEC=0
#include "ConnectionCount.inc"
      COUNTS=T2_NB_CONNEC
      END SUBROUTINE
