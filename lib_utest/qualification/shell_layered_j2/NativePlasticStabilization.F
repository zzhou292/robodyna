! Prescribed post-material state into the unchanged pinned CZFINTN1 NPT3 body.
! Reuses native geometry/material/packing modules; no whole solver or point law.
! OpenRadioss (C) 2026 Siemens, AGPL-3.0-or-later.
      SUBROUTINE QE_PLASTIC_STABILIZATION(X,V,VR,MATERIAL,BASE_HISTORY,
     . STEP,FACTORS,YIELD,OUTPUT,STATUS) BIND(C,NAME="qeph_plastic_stabilization")
      USE ISO_C_BINDING, ONLY: C_DOUBLE,C_INT
      USE QE_Q1_GEOMETRY_MOD, ONLY: QE_GEOMETRY_,QE_PREPARE_GEOMETRY
      USE QE_Q2_HISTORY_MOD, ONLY: QE_HISTORY_,QE_UNPACK_HISTORY,QE_PACK_HISTORY
      USE QE_Q2_MATERIAL_MOD, ONLY: QE_MATERIAL_,QE_PREPARE_MATERIAL
#include "implicit_f.inc"
#include "mvsiz_p.inc"
      REAL(C_DOUBLE),INTENT(IN) :: X(3,4),V(3,4),VR(3,4),MATERIAL(4),
     . BASE_HISTORY(38),STEP,FACTORS(2),YIELD
      REAL(C_DOUBLE),INTENT(OUT) :: OUTPUT(62)
      INTEGER(C_INT),INTENT(OUT) :: STATUS
      TYPE(QE_GEOMETRY_) GEOMETRY
      TYPE(QE_HISTORY_) H
      TYPE(QE_MATERIAL_) M
      MY_REAL FAC(MVSIZ,2),VF(MVSIZ,3,4),VM(MVSIZ,2,4),
     . FORCE(MVSIZ,3,4),COUPLE(MVSIZ,3,4),SIGY(MVSIZ),FAC1(MVSIZ),
     . FZERO(3,4,1),VMZ(MVSIZ,4)
      INTEGER IPARTC(MVSIZ),J,K
      CALL QE_PREPARE_GEOMETRY(X,V,VR,MATERIAL(4),STEP,GEOMETRY,STATUS)
      IF(STATUS/=0) RETURN
      CALL QE_UNPACK_HISTORY(BASE_HISTORY,H)
      CALL QE_PREPARE_MATERIAL(MATERIAL,GEOMETRY%AREA,H%THK,STEP,M)
      VF=ZERO
      VM=ZERO
      SIGY=YIELD
      FAC(:,1)=FACTORS(1)
      FAC(:,2)=FACTORS(2)
      FAC1=ONE
      IPARTC=1
      FZERO=ZERO
      VMZ=ZERO
      FORCE=ZERO
      COUPLE=ZERO
      CALL QE_Q1_CZFINTCE(1,1,M%THK0,M%THK02,GEOMETRY%AREA_I,
     . GEOMETRY%X13,GEOMETRY%X24,GEOMETRY%Y13,GEOMETRY%Y24,GEOMETRY%Z1,
     . GEOMETRY%MX23,GEOMETRY%MX13,GEOMETRY%MX34,
     . GEOMETRY%MY13,GEOMETRY%MY23,GEOMETRY%MY34,H%FOR,H%MOM,VF,VM,1)
      CALL QE_Q1_CZFINTN1(1,1,M%THK0,M%THK02,GEOMETRY%AREA_I,GEOMETRY%VHG,
     . GEOMETRY%X13,GEOMETRY%X24,GEOMETRY%Y13,GEOMETRY%Y24,GEOMETRY%Z1,
     . GEOMETRY%MX23,GEOMETRY%MX13,GEOMETRY%MX34,
     . GEOMETRY%MY13,GEOMETRY%MY23,GEOMETRY%MY34,H%HOURG,H%FOR,H%MOM,
     . VF,VM,FAC,M%A11,M%A12,M%G,M%SHF,SIGY,GEOMETRY%OFF,FAC1,
     . M%RHO,GEOMETRY%AREA,STEP,H%EINT,M%AMU,GEOMETRY%VHI,3,IPARTC,
     . H%EVIS,0,M%GSR,1,M%A11SR,M%A12SR,M%NUSR,M%SHFSR,44,M%FAC58)
      CALL QE_Q1_CZPROJN(1,1,GEOMETRY%VQN,GEOMETRY%VQ,VF,VM,GEOMETRY%PLAT,
     . FORCE(1,1,1),FORCE(1,1,2),FORCE(1,1,3),FORCE(1,1,4),
     . FORCE(1,2,1),FORCE(1,2,2),FORCE(1,2,3),FORCE(1,2,4),
     . FORCE(1,3,1),FORCE(1,3,2),FORCE(1,3,3),FORCE(1,3,4),
     . COUPLE(1,1,1),COUPLE(1,1,2),COUPLE(1,1,3),COUPLE(1,1,4),
     . COUPLE(1,2,1),COUPLE(1,2,2),COUPLE(1,2,3),COUPLE(1,2,4),
     . COUPLE(1,3,1),COUPLE(1,3,2),COUPLE(1,3,3),COUPLE(1,3,4),
     . FZERO,GEOMETRY%Z1,GEOMETRY%COREL,GEOMETRY%DI,GEOMETRY%DB,0,0,
     . GEOMETRY%DIZ,VMZ)
      CALL QE_PACK_HISTORY(H,OUTPUT(1:38))
      DO J=1,4
        K=39+3*(J-1)
        OUTPUT(K:K+2)=FORCE(1,:,J)
        K=51+3*(J-1)
        OUTPUT(K:K+2)=COUPLE(1,:,J)
      END DO
      STATUS=0
      END
