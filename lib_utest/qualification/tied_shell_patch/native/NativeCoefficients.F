C     Test packet. Geometry and coefficient extracts are exact pinned source.
      SUBROUTINE TL_TIED_COEFFICIENTS(X,SECONDARY,INITIAL_INER,
     . REPEATED,RESULT) BIND(C,NAME="tl_tied_patch_coefficients")
      USE ISO_C_BINDING
      IMPLICIT NONE
      REAL(C_DOUBLE), INTENT(IN) :: X(3,5),SECONDARY(4),INITIAL_INER(4)
      REAL(C_DOUBLE), INTENT(OUT) :: RESULT(24)
      INTEGER(C_INT), INTENT(IN) :: REPEATED
      INTEGER, PARAMETER :: I=5,II=1,J1=1,J2=2,J3=3
      INTEGER, PARAMETER :: IRODDL=1,IDEL2=1
      INTEGER J4,J,WEIGHT(5),ANIM_N(2),OUTP_N(2)
      TYPE OUTPUT_OPTIONS
        INTEGER N_SCAL_DMAS
      END TYPE
      TYPE(OUTPUT_OPTIONS) H3D_DATA
      REAL(C_DOUBLE), PARAMETER :: ONE=1D0,TWO=2D0,ZERO=0D0
      REAL(C_DOUBLE), PARAMETER :: FOURTH=.25D0,FOUR=4D0
      REAL(C_DOUBLE), PARAMETER :: EM20=ONE/1D20
      REAL(C_DOUBLE) DPARA(7,1),MS(5),IN(5),MINER(5)
      REAL(C_DOUBLE) STIFN(5),STIFR(5),ADM(5),DMAST,SMASS(1),SINER(1)
      REAL(C_DOUBLE) X0,X1,X2,X3,X4,XS,Y0,Y1,Y2,Y3,Y4,YS
      REAL(C_DOUBLE) Z0,Z1,Z2,Z3,Z4,ZS
      REAL(C_DOUBLE) X12,X22,X32,X42,Y12,Y22,Y32,Y42
      REAL(C_DOUBLE) Z12,Z22,Z32,Z42,XX,YY,ZZ,XY,YZ,ZX
      REAL(C_DOUBLE) XXX,YYY,ZZZ,XY2,YZ2,ZX2,DET
      REAL(C_DOUBLE) B1,B2,B3,C1,C2,C3,XMSI,INS,INX,MRX,MRY,MRZ
      REAL(C_DOUBLE) MR,FACT,STF
      J4=4
      IF (REPEATED==1) J4=3
      WEIGHT=1
      MS=ZERO;IN=ZERO;MINER=ZERO;STIFN=ZERO;STIFR=ZERO;ADM=ZERO
      DMAST=ZERO;SMASS=ZERO;SINER=ZERO
      ANIM_N=0;OUTP_N=0;H3D_DATA%N_SCAL_DMAS=1
      MS(I)=SECONDARY(1);IN(I)=SECONDARY(2)
      STIFN(I)=SECONDARY(3);STIFR(I)=SECONDARY(4)
      MINER(1:4)=INITIAL_INER
#include "Geometry.inc"
C     Same selected input setup as I2FOR28_CIN387 and 393. No force needed.
      XMSI=MS(I)*WEIGHT(I)
      INS=IN(I)*WEIGHT(I)
#include "Coefficients.inc"
      DO J=1,5
        RESULT(4*J-3)=MS(J)
        RESULT(4*J-2)=IN(J)
        RESULT(4*J-1)=STIFN(J)
        RESULT(4*J)=STIFR(J)
      ENDDO
      RESULT(21)=SMASS(1);RESULT(22)=SINER(1)
      RESULT(23)=DMAST;RESULT(24)=SUM(ADM)
      END
