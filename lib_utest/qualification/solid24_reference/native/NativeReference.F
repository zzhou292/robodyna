! Complete selected SCOOR3 -> SJACIDP -> SRCOOR3 geometry/mass packet.
      SUBROUTINE SOLID24_REFERENCE_CORE(X,RHO0,VALUES,PERM,STATUS,MODE,JAC_OUT)
      USE ISO_C_BINDING
      USE SOLID24_REF_ELEMENT_MOD, ONLY: NIXS
      USE SOLID24_REF_MESSAGE_MOD, ONLY: GEOMETRY_ERRORS
#include "implicit_f.inc"
#include "mvsiz_p.inc"
#include "param_c.inc"
#include "com01_c.inc"
#include "vect01_c.inc"
#include "scr05_c.inc"
#include "scr03_c.inc"
#include "com04_c.inc"
      REAL(C_DOUBLE), INTENT(IN) :: X(3,8),RHO0
      REAL(C_DOUBLE), INTENT(OUT) :: VALUES(44)
      INTEGER(C_INT), INTENT(OUT) :: PERM(8),STATUS
      INTEGER, INTENT(IN) :: MODE
      REAL(C_DOUBLE), INTENT(OUT) :: JAC_OUT(10)
      REAL(C_DOUBLE) XREFS(8,3,1),TEMP0(MVSIZ),TEMP(8),JAC_I(10,1)
      INTEGER I,J,K,N,IXS(NIXS,1),MXT(1),NGEO(1),NGL(1)
      INTEGER IPART(1),IGEO(1,1),JHBE
      REAL(C_DOUBLE) PX(4,1),PY(4,1),PZ(4,1),VOLDP(1)
      REAL(C_DOUBLE) INER(8),VR(3,8),INS(8,1),RHOF(1),FRAC(1),FILL(1)
      REAL(C_DOUBLE) SOLID24_REF_CHECKVOLUME_8N,XL,YL,ZL
      REAL(C_DOUBLE) V(3,8),RHO(1),VOLU(1),VEUL(51,1),DET(1)
      REAL(C_DOUBLE) DELTAX(1),GEO(12,1),PARTSAV(20,1),MSS(8,1)
      REAL(C_DOUBLE) MS(8),MSNF(8),MSSF(8,1),WMA(8),RHOCP(1)
      REAL(C_DOUBLE) MCP(8),MCPS(8,1),MSSA(8)
      REAL(C_DOUBLE) X1(MVSIZ),X2(MVSIZ),X3(MVSIZ),X4(MVSIZ),X5(MVSIZ),X6(MVSIZ),X7(MVSIZ),X8(MVSIZ)
      REAL(C_DOUBLE) XD1(MVSIZ),XD2(MVSIZ),XD3(MVSIZ),XD4(MVSIZ),XD5(MVSIZ),XD6(MVSIZ),XD7(MVSIZ),XD8(MVSIZ)
      REAL(C_DOUBLE) Y1(MVSIZ),Y2(MVSIZ),Y3(MVSIZ),Y4(MVSIZ),Y5(MVSIZ),Y6(MVSIZ),Y7(MVSIZ),Y8(MVSIZ)
      REAL(C_DOUBLE) YD1(MVSIZ),YD2(MVSIZ),YD3(MVSIZ),YD4(MVSIZ),YD5(MVSIZ),YD6(MVSIZ),YD7(MVSIZ),YD8(MVSIZ)
      REAL(C_DOUBLE) Z1(MVSIZ),Z2(MVSIZ),Z3(MVSIZ),Z4(MVSIZ),Z5(MVSIZ),Z6(MVSIZ),Z7(MVSIZ),Z8(MVSIZ)
      REAL(C_DOUBLE) ZD1(MVSIZ),ZD2(MVSIZ),ZD3(MVSIZ),ZD4(MVSIZ),ZD5(MVSIZ),ZD6(MVSIZ),ZD7(MVSIZ),ZD8(MVSIZ)
      INTEGER IX1(MVSIZ),IX2(MVSIZ),IX3(MVSIZ),IX4(MVSIZ),IX5(MVSIZ),IX6(MVSIZ),IX7(MVSIZ),IX8(MVSIZ)
      REAL(C_DOUBLE) RX(MVSIZ),RY(MVSIZ),RZ(MVSIZ),SX(MVSIZ),SY(MVSIZ),SZ(MVSIZ),TX(MVSIZ),TY(MVSIZ),TZ(MVSIZ)
      REAL(C_DOUBLE) E1X(MVSIZ),E1Y(MVSIZ),E1Z(MVSIZ),E2X(MVSIZ),E2Y(MVSIZ),E2Z(MVSIZ),E3X(MVSIZ),E3Y(MVSIZ),E3Z(MVSIZ)
      REAL(C_DOUBLE) F1X(MVSIZ),F1Y(MVSIZ),F1Z(MVSIZ),F2X(MVSIZ),F2Y(MVSIZ),F2Z(MVSIZ)
#include "coordinate_interfaces.inc"
      XREFS=ZERO
      TEMP0=ZERO
      TEMP=ZERO
      JAC_OUT=ZERO
      NXREF=0
      JCLOS=0
      NUMNOD=8
      LFT=1
      LLT=1
      NFT=0
      JALE=0
      JEUL=0
      JTHE=0
      ISROT=0
      IRODDL=0
      ISORTH=0
      IREST_MSELT=0
      JHBE=24
      NPROPG=12
      NPROPGI=1
      IXS=1
      DO N=1,8
        IXS(N+1,1)=N
      ENDDO
      STATUS=0
      VALUES=ZERO
      PERM=0
      IF(SOLID24_REF_CHECKVOLUME_8N(X,IXS(:,1))==ZERO)THEN
        STATUS=1
        RETURN
      ENDIF
      IF(MODE==10)THEN
      CALL SOLID24_REF_SCOOR3(X,XREFS,IXS,GEO,MXT,NGEO,NGL,
     . IX1,IX2,IX3,IX4,IX5,IX6,IX7,IX8,
     . X1,X2,X3,X4,X5,X6,X7,X8,
     . Y1,Y2,Y3,Y4,Y5,Y6,Y7,Y8,
     . Z1,Z2,Z3,Z4,Z5,Z6,Z7,Z8,
     . RX,RY,RZ,SX,SY,SZ,TX,TY,TZ,
     . E1X,E1Y,E1Z,E2X,E2Y,E2Z,E3X,E3Y,E3Z,
     . F1X,F1Y,F1Z,F2X,F2Y,F2Z,TEMP0,TEMP,0,
     . XD1,XD2,XD3,XD4,XD5,XD6,XD7,XD8,
     . YD1,YD2,YD3,YD4,YD5,YD6,YD7,YD8,
     . ZD1,ZD2,ZD3,ZD4,ZD5,ZD6,ZD7,ZD8)
      CALL SOLID24_REF_SJACIDP(XD1,XD2,XD3,XD4,XD5,XD6,XD7,XD8,
     . YD1,YD2,YD3,YD4,YD5,YD6,YD7,YD8,
     . ZD1,ZD2,ZD3,ZD4,ZD5,ZD6,ZD7,ZD8,
     . JAC_I,1)
      JAC_OUT=JAC_I(:,1)
      ENDIF
      CALL SOLID24_REF_SRCOOR3(X,XREFS,IXS,GEO,MXT,NGEO,NGL,JHBE,
     . IX1,IX2,IX3,IX4,IX5,IX6,IX7,IX8,
     . X1,X2,X3,X4,X5,X6,X7,X8,
     . Y1,Y2,Y3,Y4,Y5,Y6,Y7,Y8,
     . Z1,Z2,Z3,Z4,Z5,Z6,Z7,Z8,
     . RX,RY,RZ,SX,SY,SZ,TX,TY,TZ,
     . E1X,E1Y,E1Z,E2X,E2Y,E2Z,E3X,E3Y,E3Z,
     . F1X,F1Y,F1Z,F2X,F2Y,F2Z,TEMP0,TEMP,0,
     . XD1,XD2,XD3,XD4,XD5,XD6,XD7,XD8,
     . YD1,YD2,YD3,YD4,YD5,YD6,YD7,YD8,
     . ZD1,ZD2,ZD3,ZD4,ZD5,ZD6,ZD7,ZD8)
      GEO=ZERO
      GEO(12,1)=14
      IGEO=0
      VEUL=ZERO
      GEOMETRY_ERRORS=0
      CALL SOLID24_REF_SZDERI3(VOLU,VEUL,GEO,IGEO,
     . XD1,XD2,XD3,XD4,XD5,XD6,XD7,XD8,
     . YD1,YD2,YD3,YD4,YD5,YD6,YD7,YD8,
     . ZD1,ZD2,ZD3,ZD4,ZD5,ZD6,ZD7,ZD8,
     . PX(1,1),PX(2,1),PX(3,1),PX(4,1),
     . PY(1,1),PY(2,1),PY(3,1),PY(4,1),
     . PZ(1,1),PZ(2,1),PZ(3,1),PZ(4,1),
     . RX,RY,RZ,SX,SY,SZ,TZ,NGL,NGEO,DET,VOLDP,1,0,0)
      CALL SOLID24_REF_SDLEN3(
     . X1,X2,X3,X4,X5,X6,X7,X8,
     . Y1,Y2,Y3,Y4,Y5,Y6,Y7,Y8,
     . Z1,Z2,Z3,Z4,Z5,Z6,Z7,Z8,DELTAX,DET)
      IF(GEOMETRY_ERRORS/=0)THEN
        STATUS=GEOMETRY_ERRORS
        RETURN
      ENDIF
      RHO(1)=RHO0
      V=ZERO
      PARTSAV=ZERO
      MS=ZERO
      MSS=ZERO
      MSNF=ZERO
      MSSF=ZERO
      WMA=ZERO
      RHOCP=ZERO
      MCP=ZERO
      MCPS=ZERO
      MSSA=ZERO
      IPART=1
      INER=ZERO
      VR=ZERO
      INS=ZERO
      RHOF=ZERO
      FRAC=ZERO
      FILL=ONE
      CALL SOLID24_REF_SMASS3(RHO,MS,PARTSAV,X,V,IPART,MSS,DET,
     . MSNF,MSSF,INER,VR,INS,WMA,RHOCP,MCP,MCPS,MSSA,RHOF,FRAC,FILL,
     . IX1,IX2,IX3,IX4,IX5,IX6,IX7,IX8)
C     Observation packing only. Frame is row-major with native axes in columns.
      VALUES(1)=E1X(1)
      VALUES(2)=E2X(1)
      VALUES(3)=E3X(1)
      VALUES(4)=E1Y(1)
      VALUES(5)=E2Y(1)
      VALUES(6)=E3Y(1)
      VALUES(7)=E1Z(1)
      VALUES(8)=E2Z(1)
      VALUES(9)=E3Z(1)
      VALUES(10)=X1(1)
      VALUES(11)=Y1(1)
      VALUES(12)=Z1(1)
      VALUES(13)=X2(1)
      VALUES(14)=Y2(1)
      VALUES(15)=Z2(1)
      VALUES(16)=X3(1)
      VALUES(17)=Y3(1)
      VALUES(18)=Z3(1)
      VALUES(19)=X4(1)
      VALUES(20)=Y4(1)
      VALUES(21)=Z4(1)
      VALUES(22)=X5(1)
      VALUES(23)=Y5(1)
      VALUES(24)=Z5(1)
      VALUES(25)=X6(1)
      VALUES(26)=Y6(1)
      VALUES(27)=Z6(1)
      VALUES(28)=X7(1)
      VALUES(29)=Y7(1)
      VALUES(30)=Z7(1)
      VALUES(31)=X8(1)
      VALUES(32)=Y8(1)
      VALUES(33)=Z8(1)
      VALUES(34)=VOLU(1)
      VALUES(35)=DELTAX(1)
      DO N=1,8
        J=IXS(N+1,1)
        PERM(N)=J-1
        VALUES(35+J)=MSS(N,1)
      ENDDO
      VALUES(44)=PARTSAV(1,1)
      END SUBROUTINE

      SUBROUTINE SOLID24_REFERENCE_NATIVE(X,RHO0,VALUES,PERM,STATUS)
     . BIND(C,NAME="solid24_reference_native")
      USE ISO_C_BINDING
      IMPLICIT NONE
      REAL(C_DOUBLE),INTENT(IN) :: X(3,8),RHO0
      REAL(C_DOUBLE),INTENT(OUT) :: VALUES(44)
      INTEGER(C_INT),INTENT(OUT) :: PERM(8),STATUS
      REAL(C_DOUBLE) JAC(10)
      CALL SOLID24_REFERENCE_CORE(X,RHO0,VALUES,PERM,STATUS,0,JAC)
      END SUBROUTINE

      SUBROUTINE SOLID24_REFERENCE_GLOBAL_NATIVE(X,RHO0,VALUES,PERM,STATUS)
     . BIND(C,NAME="solid24_reference_global_native")
      USE ISO_C_BINDING
      IMPLICIT NONE
      REAL(C_DOUBLE),INTENT(IN) :: X(3,8),RHO0
      REAL(C_DOUBLE),INTENT(OUT) :: VALUES(54)
      INTEGER(C_INT),INTENT(OUT) :: PERM(8),STATUS
      CALL SOLID24_REFERENCE_CORE(X,RHO0,VALUES(1:44),PERM,STATUS,10,VALUES(45:54))
      END SUBROUTINE
